// ── pop ────────────────────────────────────────────────────────────────────
// Обратный push: убирает последний элемент из массива и возвращает его.
// Массив меняется, как и при push.
const caseIds = ['C1', 'C2', 'C3'];
const last = caseIds.pop();
console.log('1)', last, caseIds.length); // 1) C3 2

// ── do...while ─────────────────────────────────────────────────────────────
// Как while, но условие проверяется ПОСЛЕ прохода, поэтому тело выполнится
// хотя бы один раз — даже если условие ложно с самого начала.
let runs = 0;
do {
  runs++;
} while (runs > 100);
console.log('2)', runs); // 2) 1

// ── for (;;) ───────────────────────────────────────────────────────────────
// Все три части заголовка for необязательны. Без условия цикл бесконечен —
// выйти из него можно только через break. Пишут так редко.
let attempt = 0;
for (;;) {
  attempt++;
  if (attempt === 3) {
    break;
  }
}
console.log('3)', attempt); // 3) 3

// ── Зачем сравнивать строки: sort ──────────────────────────────────────────
// Сравнение строк чаще всего живёт внутри сортировки. У массива есть метод
// sort. Без аргументов он сортирует строки по кодам символов — как < в
// 01-comparisons.ts: заглавные раньше строчных, «ё» после «я».
const titles = ['banana', 'Cherry', 'apple'];
console.log('4)', [...titles].sort().join(' ')); // 4) Cherry apple banana

// Свой порядок задают функцией сравнения. Она получает два элемента
// и должна вернуть ЧИСЛО: меньше нуля — a раньше b, больше нуля — b раньше a,
// ноль — порядок не важен. Для текста такое число даёт a.localeCompare(b):
// сравнение по правилам языка, без «заглавные раньше».
console.log('5)', [...titles].sort((a, b) => a.localeCompare(b)).join(' ')); // 5) apple banana Cherry

// Вернуть true/false вместо числа — частая ошибка: true станет 1, false — 0,
// а «меньше нуля» не придёт никогда, и массив не отсортируется. TypeScript её ловит:
// ❌ TS2345: Argument of type '(a: string, b: string) => boolean' is not assignable to parameter of type '(a: string, b: string) => number'.
// titles.sort((a, b) => a < b);

// Как устроены функции и стрелочная запись (a, b) => … — урок 4.
// [...titles] — копия массива: sort меняет массив, на котором вызван.
// Копии и ... — урок про объекты.

// ── Тип «или»: значения пока нет ───────────────────────────────────────────
// Значение посчитают позже, а пока его нет. Тип «число или null» —
// number | null. | в типе — не логическое ИЛИ, а объединение типов:
// «здесь лежит значение одного из этих типов». Подробно — урок про union.
let durationMs: number | null = null;
console.log('6)', durationMs); // 6) null
durationMs = 1500;
console.log('7)', durationMs); // 7) 1500

