/**
 * Урок 3 · Сравнения.
 *
 * Что здесь: `<`, `>`, `<=`, `>=`, `!==` · как сравниваются строки ·
 * строка-число против числа · `'0'` истинное, и всё же `0 == '0'` — правда.
 *
 *   node lessons/lesson-03/examples/01-comparisons.ts   запустить
 *   yarn typecheck                                      проверить типы
 *
 * Число со строкой TypeScript сравнить не даст (TS2367), поэтому то, что
 * делает с ними сам JavaScript, показано через node -e: node типы не проверяет.
 *
 *   node -e "console.log(0 == '0', '1e1' == 10, '10' == '1e1')"   → true true false
 */

// ── Сравнение даёт true или false ──────────────────────────────────────────
console.log('1)', 2 < 2, 2 <= 2, 2 > 1, 2 >= 3, 2 !== 2); // 1) false true true false false

// ── Строки сравниваются по кодам символов ──────────────────────────────────
// У каждого символа есть номер. Строки сравниваются символ за символом
// слева направо, по этим номерам. Для латиницы номера идут по алфавиту,
// но все заглавные стоят раньше всех строчных.
console.log('2)', 'apple' < 'banana', 'Book' < 'book', 'Zebra' < 'apple'); // 2) true true true

// Сравнить текст без учёта регистра — привести обе стороны к одному регистру.
const typedTitle: string = 'Book';
console.log('3)', typedTitle.toLowerCase() === 'book'); // 3) true

// Номера — это не алфавит: в кириллице «ё» стоит после «я».
console.log('4)', 'ё' > 'я', 'ёлка' > 'яблоко'); // 4) true true

// ── Строка-число против числа ──────────────────────────────────────────────
// Со страницы цифры приходят строкой. Две строки < сравнивает по символам:
// '1' раньше '9', значит, '10' «меньше». Числа — только после Number(…).
console.log('5)', '10' < '9', 10 < 9, Number('10') < 9); // 5) true false false

// ── '0' — истинное ─────────────────────────────────────────────────────────
// Ложных значений восемь (урок 2), '0' среди них нет: непустая строка
// истинная, что бы в ней ни было написано.
console.log('6)', Boolean(0), Boolean('0'), Boolean('false'), Boolean(' ')); // 6) false true true true

// ── ...и всё же 0 == '0' ───────────────────────────────────────────────────
// == приводит СТРОКУ К ЧИСЛУ (не наоборот): '0' → 0, и значения равны.
// Ложное «равно» истинному. Поэтому всегда ===.
// ❌ TS2367: This comparison appears to be unintentional because the types 'number' and 'string' have no overlap.
// console.log(0 == '0');
const zero: number = 0;
console.log('7)', zero === Number('0'), Boolean(zero) === Boolean('0')); // 7) true false

