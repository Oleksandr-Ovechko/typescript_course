/**
 * Урок 3 · Логика: `&&`, `||`, `!`.
 *
 * Что здесь: три логических оператора · порядок, в котором они считаются ·
 * `||` и `&&` возвращают не `true`/`false`, а один из операндов ·
 * разделитель `_` в числах.
 *
 *   node lessons/lesson-03/examples/02-logic.ts   запустить
 *   yarn typecheck                                проверить типы
 */

// ── Два условия в одном ────────────────────────────────────────────────────
// a && b — «и»: true, когда обе стороны true.
// a || b — «или»: true, когда хотя бы одна true.
// !a     — «не»: переворачивает true в false и обратно.
console.log('1)', true && false, true || false, !true); // 1) false true false

// Порядок: сначала !, потом сравнения, потом &&, потом ||.
// Скобки здесь не нужны: 2 > 1 && … — это (2 > 1) && …
console.log('2)', 2 > 1 && 'Book' < 'book', 2 > 3 || 2 > 1); // 2) true true

// ! стоит раньше сравнений, поэтому сравнение, которое нужно перевернуть, — в скобки.
const total: number = 15;
console.log('3)', !(total > 10), total > 10 && total < 20, total < 10 || total === 15); // 3) false true true

// ── || и && возвращают значение ────────────────────────────────────────────
// Сокращённое вычисление: идут слева направо и останавливаются, как только
// ответ известен. Возвращают тот операнд, на котором остановились.
//   a || b — первое ИСТИННОЕ: a, если оно truthy, иначе b
//   a && b — первое ЛОЖНОЕ:   a, если оно falsy,  иначе b
const typedName: string = '';
const savedName: string = 'Ann';
const otherName: string = 'Bob';
console.log('4)', typedName || 'гость', savedName || 'гость'); // 4) гость Ann
console.log('5)', savedName && otherName, savedName || otherName); // 5) Bob Ann
console.log('6)', typedName && 'не напечатается'); // 6)
// В 6) && остановился на пустой строке и вернул её — поэтому после «6)» пусто.

// ── Ловушка: ноль тоже ложный ──────────────────────────────────────────────
// Хотели «таймаут 0 — не ждать», а || заменил ноль на 30 секунд.
// Для «подставь, только если значения нет вовсе» есть ?? — см. 04-nullish.ts.
const timeoutMs: number = 0;
console.log('7)', timeoutMs || 30_000, timeoutMs && 'не ноль'); // 7) 30000 0

// ── Разделитель в числах ───────────────────────────────────────────────────
// _ внутри числа — только для глаз: на значение не влияет. Работает в целых,
// дробных и шестнадцатеричных числах (с приставкой 0x).
console.log('8)', 1_000_000, 0.000_5, 0xff_ff); // 8) 1000000 0.0005 65535

