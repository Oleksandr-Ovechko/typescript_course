/**
 * Урок 3 · Блок 1 (продолжение) — функция как значение и колбэк.
 *
 * Что здесь: массив функций и `Array<(a: number) => number>` · `for...of` ·
 * `map`, `filter`, `find` и что каждый возвращает · своя функция, принимающая
 * колбэк · вынесение колбэка в переменную · где колбэк в самом тесте.
 *
 *   node lessons/lesson-03/examples/03-functions-as-values.ts
 *   yarn typecheck
 */

// ── Функция — такое же значение, как число или строка ──────────────────────
// Её можно положить в переменную, в поле объекта, в массив — и передать
// в другую функцию. Последнее и есть колбэк.
const operations: Array<(a: number) => number> = [
  (a) => a + 1,
  (a) => a - 1,
  (a) => a * a,
];

// Тип читается так: массив, элемент — функция, принимающая число и
// возвращающая число. Угловые скобки здесь — те же дженерики из урока 2:
// `Array<T>` с подставленным типом элемента.
for (const operation of operations) {
  console.log('operation(5) =', operation(5));
}

// ── map, filter, find ──────────────────────────────────────────────────────
// Все трое устроены одинаково: проходят по каждому элементу и на каждом
// вызывают колбэк, который вы им передали. Разница — что они делают
// с его результатом.
const spots = [3, 0, 12, 25];

const doubled = spots.map((spot) => spot * 2);
const free = spots.filter((spot) => spot === 0);
const firstFree = spots.find((spot) => spot === 0);

console.log('map   :', doubled, '← новый массив, исходный не тронут:', spots);
console.log('filter:', free, '← все подходящие');
console.log('find  :', firstFree, '← первый подходящий');

// `filter` оставляет те элементы, на которых колбэк вернул truthy. Короткая
// запись `(spot) => spot === 0` — то же самое, что развёрнутая:
const freeVerbose = spots.filter((spot) => {
  if (spot === 0) {
    return true;
  }
  return false;
});
console.log('короткая и развёрнутая запись совпадают:', String(free) === String(freeVerbose));

// А `find`, если ничего не нашёл, возвращает `undefined` — и тип это знает.
// Поэтому рядом с ним почти всегда стоит `??` из блока 0.
const missing = spots.find((spot) => spot === 777);
console.log('find не нашёл:', missing, '· с подстраховкой:', missing ?? -1);

// ── Своя функция, принимающая колбэк ───────────────────────────────────────
// Пишете колбэк вы, а вызывает его принимающая сторона — столько раз,
// сколько сочтёт нужным.
function repeat(times: number, callback: (index: number) => void): void {
  for (let i = 0; i < times; i += 1) {
    callback(i);
  }
}

repeat(3, (index) => console.log('проход №', index + 1));

// Место, в котором чаще всего путаются: колбэк объявлен без аргумента, а внутрь
// него что-то приходит. Приходит оно от того, кто колбэк вызывает — вот отсюда:
// `callback(i)`. Если вынести колбэк в переменную, это становится очевиднее.
const printIndex = (index: number): void => {
  console.log('вынесенный колбэк, индекс:', index);
};
repeat(2, printIndex);

// ── Где колбэк в самом тесте ───────────────────────────────────────────────
// test.describe('название', () => { ... })
//                ^^^^^^^^^^  ^^^^^^^^^^^^
//                 1-й арг     2-й аргумент — колбэк
//
// Ровно та же конструкция, что и `repeat` выше: строка и функция. Playwright
// вызовет её сам — сразу при загрузке файла, когда собирает список тестов;
// колбэки самих `test(...)` он вызовет позже. Размер тела значения не имеет —
// важно лишь то, что вы передаёте функцию, а не вызываете её.
function describe(title: string, body: () => void): void {
  console.log(`describe('${title}') → вызываю тело`);
  body();
}

describe('[C154005][Lead Capture] Verify Form Settings', () => {
  console.log('  внутри колбэка: здесь стояли бы тесты');
});

