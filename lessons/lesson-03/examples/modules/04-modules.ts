// ── Относительный путь против голого ───────────────────────────────────────
// В тестах встречаются четыре вида строки после `from`. Различаются они
// не собачкой, а формой пути:
//
//   './C154005.helpers'                       файл рядом, в этой же папке
//   '../../../helpers/widgets-wl-ui-helper'   файл выше по дереву
//   '@playwright/test'                        голый путь → идём в node_modules
//   'wl-e2e-automation-helpers/monolith/...'  голый путь → тоже node_modules
//
// Распространённое заблуждение — что `@` означает «из node_modules». Не означает.
// `@` это часть ИМЕНИ пакета (scoped package — неймспейс в npm), и локальный
// пакет монорепы лежит в `node_modules` ровно так же. Проверяется одной командой
// в корне `wl-e2e`:
//
//   $ ls -la node_modules | grep wl-e2e
//   wl-e2e-automation-helpers -> ../helpers
//
// Yarn положил туда симлинк на папку `helpers/`. Правило простое: путь
// начинается с точки — файл рядом; не начинается — ищем в node_modules.

// ── Зачем в примерах курса стоит пустой export ─────────────────────────────
// Файл, в котором нет ни одного import или export, — не модуль, а глобальный
// скрипт. Его объявления верхнего уровня попадают в общую область видимости
// со всеми такими же файлами, и одинаковые имена начинают конфликтовать:
// `TS2393` для функций, `TS2451` для `const` и `let`.
//
// Уточнение к тому, что прозвучало на занятии: файлы при этом никуда не
// склеиваются и ни в какой общий JS не собираются. При `noEmit` компилятор
// вообще не создаёт файлов, а `node` запустит каждый из них как ни в чём
// не бывало — типов в рантайме нет, это ровно вывод урока 2.
//
// В этом файле пустой export не нужен: выше уже есть настоящие `import`.
