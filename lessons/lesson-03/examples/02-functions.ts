/**
 * Урок 3 · Блок 1 — три способа объявить функцию.
 *
 * Что здесь: объявление, выражение, стрелочная · чем они отличаются на самом
 * деле · хостинг и мёртвая зона · возврат объекта из стрелки требует скобок ·
 * `void` и подвох с колбэком.
 *
 *   node lessons/lesson-03/examples/02-functions.ts
 *   yarn typecheck
 */

// ── Объявление функции ─────────────────────────────────────────────────────
// function declaration. Именованная, начинается с ключевого слова `function`.
function addDeclared(a: number, b: number): number {
  return a + b;
}

// ── Функциональное выражение ───────────────────────────────────────────────
// function expression. Обычная переменная, в которую положили функцию.
// Сама функция имени не имеет — имя есть только у переменной.
const addExpressed = function (a: number, b: number): number {
  return a + b;
};

// ── Стрелочная функция ─────────────────────────────────────────────────────
// Появилась в ES2015. Короткая запись: параметры, стрелка, тело.
// Если тело — одно выражение, фигурные скобки и `return` не нужны.
const addArrow = (a: number, b: number): number => a + b;

console.log('три записи, один результат:', addDeclared(2, 3), addExpressed(2, 3), addArrow(2, 3));

// ── Чем они отличаются: хостинг ────────────────────────────────────────────
// Объявление функции поднимается целиком — её можно вызвать выше по файлу,
// чем она написана. Проверить легко: вызов addDeclared стоял бы здесь и работал.
console.log('вызов объявления сработает откуда угодно:', addDeclared(1, 1));

// ❌ TS2448: Block-scoped variable 'declaredLater' used before its declaration.
// console.log(declaredLater(1, 1));
const declaredLater = (a: number, b: number): number => a + b;
console.log('а переменную — только после объявления:', declaredLater(1, 1));

// Важная поправка к формулировке «переменные не поднимаются». Поднимаются —
// но до строки объявления лежат в мёртвой зоне и трогать их нельзя. Видно
// по тексту ошибки в рантайме:
//     ReferenceError: Cannot access 'declaredLater' before initialization
// Если бы переменная не поднималась, было бы «is not defined». Подробно —
// на уроке 3.5.

// ── Чем ещё отличается стрелочная ──────────────────────────────────────────
// Не только формой записи. У стрелочной нет своего `this`, нет `arguments`,
// и её нельзя вызвать через `new`:
//     const Arrow = () => {};
//     new Arrow();   → TypeError: Arrow is not a constructor
// Для чтения тестов это пока не мешает — вернёмся к этому вместе с `this`.

// ── Возврат объекта из короткой стрелки ────────────────────────────────────
// Объект и тело функции пишутся одинаково — фигурными скобками. Без круглых
// скобок компилятор читает `{` как начало тела.
const makeBad = (id: string) => {
  id;
};
const makeGood = (id: string) => ({ id });

console.log('без скобок вернулось:', makeBad('C154005'), '· со скобками:', makeGood('C154005'));

// ── void ───────────────────────────────────────────────────────────────────
// `void` — «эта функция ничего не возвращает». Компилятор следит за обещанием:
function logStep(step: string): void {
  console.log('шаг:', step);

  // ❌ TS2322: тип 'number' нельзя присвоить типу 'void'
  // return 1;
}
logStep('открыли форму');

// Подвох, о котором стоит знать заранее. Если `void` стоит в типе КОЛБЭКА,
// запрета нет: возвращённое значение просто выбрасывается.
function repeatVoid(times: number, callback: (index: number) => void): void {
  for (let i = 0; i < times; i += 1) {
    callback(i);
  }
}

// Колбэк возвращает число, а объявлен как `=> void`. Ошибки нет — и это
// не поблажка, а осознанное правило: иначе `[1, 2].forEach((n) => n)` не
// компилировался бы ни у кого.
repeatVoid(2, (index) => index * 2);
console.log('колбэк с возвратом при типе void ошибки не даёт');

