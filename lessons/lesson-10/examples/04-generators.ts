// ── Функция, которая умеет замирать ───────────────────────────────────────
// Звёздочка после function делает функцию генератором. yield — «отдать
// значение и замереть здесь до следующего запроса».
function* attemptNames(limit: number): Generator<string> {
  for (let n = 1; n <= limit; n++) yield `попытка ${n}`;
}
console.log('1)', [...attemptNames(3)]);

// Результат тот же, что у объекта attempts из 03, — только без next, value
// и done руками. Это их и пишет за нас движок.
//
// Генератор — вся функция целиком, а не цикл внутри неё. Цикл здесь только
// потому, что так удобно перечислить три попытки; с тем же успехом можно
// написать три yield подряд.

// ── Генератор — это итератор ──────────────────────────────────────────────
// Вызов генератора не выполняет тело. Он возвращает итератор — тот самый
// объект с next() из 03.
const g = attemptNames(2);
console.log('2)', g.next());
console.log('3)', g.next());
console.log('4)', g.next());

// Тот же { value, done }, что у итератора массива. Генератор — не новая
// сущность, а короткая запись того же протокола.

// ── Что делает return в генераторе ────────────────────────────────────────
// return разрешён и значит «закончить и отдать итоговое значение».
// Оно приходит ВМЕСТЕ с done: true.
function* withReturn(): Generator<string, string, unknown> {
  yield 'первый';
  yield 'второй';
  return 'ИТОГ';
}
const wr = withReturn();
console.log('5)', wr.next(), wr.next());
console.log('6)', wr.next(), '— одно значение, не «всё оставшееся»');
console.log('7)', wr.next(), '— дальше только done: true');

// А всё, что перебирает (for...of, спред, Array.from), значение с done: true
// выбрасывает:
console.log('8)', [...withReturn()], '— ИТОГ потерялся');

// Поэтому данные из генератора отдают через yield. То, что вернули через
// return, увидит только тот, кто зовёт next() руками.
//
// Это правило протокола, а не особенность генераторов: итератор, написанный
// руками, может вернуть { value: 'ИТОГ', done: true } — и спред выбросит его
// точно так же.

// ── break закрывает генератор ─────────────────────────────────────────────
// Если выйти из for...of посреди перебора, генератор не остаётся висеть
// замершим: ему посылается return, и блок finally внутри выполняется.
// Так закрывают файлы и соединения, не дочитав до конца.
function* withCleanup(): Generator<number> {
  try {
    yield 1;
    yield 2;
    yield 3;
  } finally {
    console.log('10) finally: генератор закрыт');
  }
}
for (const x of withCleanup()) {
  console.log('9) получили', x);
  if (x === 2) break;
}

// ── Ленивость ─────────────────────────────────────────────────────────────
// Внутри while (true) без выхода. Зависнет?
function* forever(): Generator<number> {
  let n = 0;
  while (true) yield (n += 1);
}
const few: number[] = [];
for (const n of forever()) {
  if (n > 4) break;
  few.push(n);
}
console.log('11)', few, '— генератор бесконечный, взяли четыре и вышли');

// Не зависает. while (true) внутри генератора не крутится сам по себе:
// он делает ровно один шаг на каждый запрос и замирает на yield.
// Никто не спросил — ничего не считается. Это и есть ленивое вычисление.
//
// ⚠️ А вот [...forever()] повесит процесс насмерть: спред просит ВСЕ значения,
// а их бесконечно много. То же с Array.from(forever()) и деструктуризацией
// с ...rest. Бесконечный генератор перебирают только с break.

// ── Генератор как метод объекта ───────────────────────────────────────────
// Самый короткий способ выполнить протокол из 03: сделать сам метод
// [Symbol.iterator] генератором.
const suite = {
  cases: ['C157112', 'C22041', 'C19877'],
  *[Symbol.iterator](): Generator<string> {
    for (const c of this.cases) yield `[${c}]`;
  },
};
console.log('12)', [...suite]);

// Заголовок *[Symbol.iterator](): Generator<string> по частям:
//   *                   — метод-генератор (у функции звёздочка стоит после function);
//   [Symbol.iterator]   — вычисляемое имя: метод называется Symbol.iterator.
//                         Безымянным он не является. Имя в кавычках,
//                         'Symbol.iterator', было бы обычной строкой, и протокол
//                         бы не сработал;
//   ()                  — параметров нет;
//   : Generator<string> — генератор уже итератор, отдельный объект с next не нужен.

