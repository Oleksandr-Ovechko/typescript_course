// ── Устарел ли Array.from ─────────────────────────────────────────────────
// Вопрос: «я читал, что Array.from — старая конструкция и лучше спред;
// почему в проекте Array.from?»
//
// Не устарел и не старше спреда: оба появились в ES2015. Старым был другой
// приём — одолжить метод массива через call (урок 6):
//
//   Array.prototype.filter.call(nodeList, (el) => ...)       // до 2015
//   Array.from(nodeList).filter((el) => ...)                  // с 2015
//   [...nodeList].filter((el) => ...)                         // с 2015
//
// Скорее всего, прочитанный совет был именно про первую строку.
//
// Между второй и третьей есть две настоящие разницы:
//   1. Array.from принимает и массивоподобное, спред — только итерируемое;
//   2. у Array.from есть второй аргумент — map прямо при создании массива.
console.log('1)', Array.from({ length: 3 }, (_, i) => `C1571${i}`));

