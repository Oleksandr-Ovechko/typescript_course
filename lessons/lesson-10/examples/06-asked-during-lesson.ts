// ── Что такое символ ──────────────────────────────────────────────────────
// Вопрос: «Symbol.iterator вижу впервые — что это и для чего?»
//
// Символ — один из семи примитивов (урок 1): значение, которое равно только самому
// себе. Используют его как ключ свойства, который не совпадёт ни с какой
// строкой и ни с каким другим символом.
const mine = Symbol('метка');
const report = { title: 'C157112', [mine]: 'служебное' };
console.log('2)', typeof mine, '·', Object.keys(report), '·', report[mine]);

// Symbol.iterator — готовый символ, который язык заводит сам. Назвать метод
// перебора строкой 'iterator' было нельзя: у кого-то такое свойство уже было,
// и старый код начал бы перебираться по-новому.
//
// В wl-e2e символов нет ни одного: ни Symbol(, ни Symbol.iterator.
// Знать нужно ровно одно — что Symbol.iterator это имя метода перебора.

// ── Чем генератор отличается от цикла ─────────────────────────────────────
// Вопрос: «если убрать yield, это был бы обычный for?»
//
// Генератор — вся функция, а не цикл внутри неё. Главное отличие: цикл
// отрабатывает целиком, от начала до конца. Генератор отдаёт одно значение
// и возвращает управление тому, кто спросил, — и продолжит, только когда
// спросят снова. Видно по порядку строк:
function* steps(): Generator<string> {
  console.log('3) генератор: считаю первое');
  yield 'A';
  console.log('5) генератор: считаю второе');
  yield 'B';
}
const s = steps();
console.log('4) снаружи получили', s.next().value, '— генератор стоит на первом yield');
console.log('6) снаружи получили', s.next().value);

// Функция с обычным циклом так не умеет: она либо доработает до конца, либо
// выйдет по return — и продолжить с того же места её уже не заставить.

// ── Десять случайных чётных ───────────────────────────────────────────────
// Пример из зала: «нужно десять случайных чётных чисел; сколько раз крутить
// цикл, заранее неизвестно — вот зачем генератор?» Хороший пример, и его
// можно решить обоими способами.
//
// Math.random() даёт каждый раз разное, поэтому здесь предсказуемый
// «случайный» генератор чисел — чтобы вывод совпадал при каждом запуске.
function makeRandom(seed: number): () => number {
  let state = seed;
  return () => {
    state = (state * 1103515245 + 12345) % 2147483648;
    return Math.floor(state / 65536) % 100;
  };
}

// Способ 1 — while: условие есть, счётчика нет. Ровно тот случай из урока.
const nextRandom = makeRandom(42);
const viaWhile: number[] = [];
while (viaWhile.length < 10) {
  const n = nextRandom();
  if (n % 2 === 0) viaWhile.push(n);
}
console.log('7) while:    ', viaWhile.join(' '));

// Способ 2 — генератор бесконечного потока чисел, и отдельно — «взять,
// пока не наберётся десять».
function* randoms(seed: number): Generator<number> {
  const next = makeRandom(seed);
  while (true) yield next();
}
const viaGenerator: number[] = [];
for (const n of randoms(42)) {
  if (n % 2 === 0) viaGenerator.push(n);
  if (viaGenerator.length === 10) break;
}
console.log('8) генератор:', viaGenerator.join(' '));

// Результат одинаковый. Разница в устройстве: во втором способе «откуда
// берутся числа» и «сколько нам надо» разнесены по двум местам. Генератор
// randoms ничего не знает про чётность и про десятку — его можно отдать
// в другой цикл с другим условием. Для одной задачи while короче и понятнее.

// ── Что быстрее ───────────────────────────────────────────────────────────
// Вопрос: «я смотрел — for намного медленнее, чем три метода подряд?»
// Наоборот. Замер на ноде 24.11: сумма удвоенных чётных из 10 000 000 чисел.
//
//   for (let i = 0; …)              ~17 мс
//   for...of                        ~80 мс
//   forEach                         ~79 мс
//   for...of по генератору         ~147 мс
//   filter → map → reduce          ~300 мс
//   генератор, первые 10 чётных      ~0 мс
//
// Обычный for — самый быстрый. Три метода подряд — самые медленные: каждый
// создаёт новый массив на миллионы элементов. Генератор проходит тот же путь
// раза в два медленнее for...of по массиву: каждый шаг — отдельный объект
// { value, done } и возврат в замершую функцию. Зато если нужно не всё,
// а первые десять, генератор считает десять — и тут не догнать никого.
//
// Цифры по времени здесь не печатаются: они разные на каждом запуске.
// Печатаются только результаты — чтобы было видно, что считают одно и то же:
const numbers = Array.from({ length: 1_000 }, (_, i) => i);

let viaFor = 0;
for (let i = 0; i < numbers.length; i++) {
  if (numbers[i] % 2 === 0) viaFor += numbers[i] * 2;
}
const viaMethods = numbers
  .filter((x) => x % 2 === 0)
  .map((x) => x * 2)
  .reduce((a, b) => a + b, 0);
console.log('9) for:', viaFor, '· filter→map→reduce:', viaMethods);

