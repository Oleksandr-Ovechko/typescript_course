// ── Шаблонная строка против + ──────────────────────────────────────────────
// Обе записи дают одну строку. В обратных кавычках (клавиша с тильдой ~)
// значение подставляется через ${…}: всё внутри фигурных скобок вычисляется.
// Без ${…} это был бы просто текст «name».
const name = 'Ann';
const withPlus = 'Привет, ' + name + '!';
const withTemplate = `Привет, ${name}!`;
console.log('1)', withPlus, withTemplate, withPlus === withTemplate); // 1) Привет, Ann! Привет, Ann! true
console.log('2)', `2 + 3 = ${2 + 3}`, '2 + 3 = ' + 2 + 3); // 2) 2 + 3 = 5 2 + 3 = 23
// Во второй записи + склеил строку с 2, а потом с 3 — получилось «23».
// В ${…} сначала посчиталось 2 + 3.

// ── console.log с массивом и с ... ─────────────────────────────────────────
// Без ... console.log получает ОДИН аргумент — массив — и печатает массив.
// С ... массив разложен на отдельные аргументы — печатаются числа через пробел.
// Сам console.log принимает сколько угодно аргументов остаточным параметром:
// в типах браузера он описан как log(...data: any[]): void.
const numbers = [1, 2, 3];
console.log('3)', numbers); // 3) [ 1, 2, 3 ]
console.log('4)', ...numbers); // 4) 1 2 3

// ── map строит новый массив ────────────────────────────────────────────────
// На занятии map мелькнул в примере с arguments. Это не «цикл для печати»:
// map вызывает колбэк для каждого элемента и собирает из того, что колбэк
// ВЕРНУЛ, новый массив. Исходный не меняется.
const doubled = numbers.map((n) => n * 2);
console.log('5)', doubled, numbers); // 5) [ 2, 4, 6 ] [ 1, 2, 3 ]
// Если колбэк ничего не возвращает (только печатает), новый массив —
// из undefined. Для обхода «просто сделать что-то с каждым» — for...of.
const printed = numbers.map((n) => {
  console.log('6) элемент', n);
});
console.log('7)', printed); // 7) [ undefined, undefined, undefined ]
// Подробно методы массива — в уроке про массивы.

// ── Колбэк значением по умолчанию ──────────────────────────────────────────
// Вопрос с занятия: можно ли не передавать действие в calculate каждый раз?
// Можно сделать его значением по умолчанию — как 'Привет' у greeting.
// Не передали — сложит. Передали — сделает то, что передали.
function calculate(a: number, b: number, operation = (x: number, y: number): number => x + y): number {
  return operation(a, b);
}
console.log('8)', calculate(6, 7), calculate(6, 7, (x, y) => x * y)); // 8) 13 42

// ── Действие внутри или снаружи ────────────────────────────────────────────
// Второй вариант ответа: если действие всегда одно и то же, параметр-функция
// не нужен — действие пишут прямо в теле.
function multiplyNumbers(a: number, b: number): number {
  return a * b;
}
console.log('9)', multiplyNumbers(6, 7)); // 9) 42
// Колбэк нужен, когда действие выбирает тот, кто вызывает: calculate одна,
// а умножить, сложить или вычесть — решают при каждом вызове.

