// ── Дробные числа ──────────────────────────────────────────────────────────
console.log('1)', 0.1 + 0.2); // 0.30000000000000004
console.log('2)', 0.1 + 0.2 === 0.3); // false

// Это не баг JavaScript — так работают дробные числа почти во всех языках.
// Число хранится в двоичной системе, а 0.1 в двоичной — бесконечная дробь,
// как 1/3 в десятичной. Её обрезают, и накапливается погрешность.

console.log('3)', 0.1 + 0.7, (0.1 + 0.7) * 10); // 0.7999999999999999 7.999999999999999

// Вот почему деньги не считают в дробных числах напрямую: их держат в целых
// (в центах) или в специальной библиотеке.

// ── Сравнение дробных ──────────────────────────────────────────────────────
console.log('4)', Math.abs(0.1 + 0.2 - 0.3) < Number.EPSILON); // true

// Number.EPSILON — расстояние между 1 и следующим представимым числом.
// Приём работает рядом с единицей; дальше от неё — уже нет:
console.log('на миллиарде:', Math.abs(1e9 + 0.1 + 0.2 - (1e9 + 0.3)) < Number.EPSILON); // false

// В тестах эпсилон не используют вовсе — там expect(...).toBeCloseTo(x, 2).
// См. 06-numbers-in-tests.ts

// ── NaN ────────────────────────────────────────────────────────────────────
function toNumber(raw: string): number {
  return Number(raw);
}

const parsed = toNumber('двенадцать');
console.log('5)', parsed, '· равно ли само себе:', parsed === parsed); // NaN · false
console.log('6)', Number.isNaN(parsed)); // true

// NaN — единственное значение в языке, не равное самому себе. Отсюда и приём
// проверки `x !== x`, истинный только для NaN. Но писать так не надо:
// есть Number.isNaN.

// ── parseInt против parseFloat против Number ───────────────────────────────
console.log('7)', parseInt('12px'), parseFloat('12px'), Number('12px')); // 12 12 NaN

// parseInt и parseFloat читают слева, пока могут, и отдают что успели.
// Number работает по принципу «либо всё, либо ничего».

console.log('8)', parseInt('12.5'), parseFloat('12.5')); // 12 12.5

// parseInt — целое. На дробном он отрезает всё после точки, и на суммах
// с копейками это уже настоящая потеря данных.

console.log(
  '9)',
  parseInt(''),
  Number(''),
  Number(null as unknown as string),
  Number(undefined),
); // NaN 0 0 NaN

// Набор несогласованностей, который надо просто знать: пустая строка для
// parseInt это NaN, а для Number — НОЛЬ. null — тоже ноль. undefined — NaN.

// Практическое следствие: пустая строка со страницы превращается Number(...)
// в ноль, и дефолт через ?? уже не сработает — ноль это не null.
const fromPage = ''; // как будто из innerText
console.log('дефолт не сработал:', Number(fromPage) ?? 10); // 0

// ── toFixed ────────────────────────────────────────────────────────────────
console.log('10)', (1.005).toFixed(2), (1.5).toFixed(0), (2.5).toFixed(0)); // 1.00 2 3
console.log('11)', typeof (1).toFixed(2), '1.00' + 1); // string 1.001

// Два сюрприза сразу.
// (1.005).toFixed(2) даёт '1.00', а не '1.01' — потому что 1.005 хранится
//   чуть меньше, чем 1.005 (см. начало файла).
// И главное: toFixed возвращает СТРОКУ. Поэтому '1.00' + 1 даёт склейку.
//
// toFixed — для вывода, не для вычислений. Нужно число обратно:
console.log('обратно в число:', Number((1.2345).toFixed(2)) + 1); // 2.23

