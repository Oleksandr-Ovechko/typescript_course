// ── Строки неизменяемы ─────────────────────────────────────────────────────
const word = 'hello';
console.log('1)', word.toUpperCase(), '· оригинал:', word); // HELLO · оригинал: hello

// Ни один строковый метод не меняет строку — все возвращают новую. Забыть
// присвоить результат — самая частая ошибка: `text.trim();` отдельной строкой
// не делает ничего.

// ── replace меняет только первое вхождение ─────────────────────────────────
console.log('2)', 'a-a'.replace('a', 'b'), 'a-a'.replaceAll('a', 'b')); // b-a b-b

// replace со строкой в первом аргументе заменяет только первое вхождение.
// Нужны все — replaceAll или регулярка с флагом /g.
console.log('регуляркой:', 'a-a'.replace(/a/g, 'b')); // b-b

// ── .length — это не количество букв ───────────────────────────────────────
// Кодовая единица — «ячейка», из которых состоит строка. Обычная буква
// занимает одну, эмодзи — две и больше. .length считает ячейки, а не символы.
console.log('3)', 'привет'.length, '👍'.length, [...'👍'].length); // 6 2 1
console.log('4)', '👨‍👩‍👧'.length, [...'👨‍👩‍👧'].length); // 8 5
console.log('5)', '👍'.slice(0, 1)); // мусор: половина эмодзи

// Спред [...'👍'] разбирает строку по настоящим символам.
// Семья — это несколько эмодзи, склеенных невидимыми соединителями:
// восемь ячеек, пять символов.
// Пятая строка — практическое следствие: slice разрезал эмодзи пополам.
// Обрезая текст со страницы по .length, можно так же сломать символ.

// Две ячейки занимает не «нелатиница», а символ за пределами основной таблицы
// Unicode. Арабские буквы и обычные иероглифы — по одной ячейке:
console.log('م 中 日本語:', 'م'.length, '中'.length, '日本語'.length); // 1 1 3

// ── Регистр и локали ───────────────────────────────────────────────────────
console.log('6)', 'i'.toUpperCase(), 'i'.toLocaleUpperCase('tr')); // I İ

// toUpperCase знает все алфавиты — 'привет' он поднимает в регистре как надо.
// Отличие toLocaleUpperCase только в правилах, зависящих от ЯЗЫКА:
// турецкая i становится İ с точкой.
console.log('обычный регистр:', 'привет'.toUpperCase(), 'ünïcode'.toUpperCase());

// ── sort() без колбэка сравнивает как строки ───────────────────────────────
console.log('7)', [10, 9, 1, 100].sort()); // [ 1, 10, 100, 9 ]
console.log('8)', [10, 9, 1, 100].sort((a, b) => a - b)); // [ 1, 9, 10, 100 ]

// Самая практичная ловушка блока. sort() без аргумента сравнивает элементы
// как строки, поэтому 100 оказывается раньше 9: сравниваются символы,
// '1' меньше '9'. Числа сортируют только с колбэком.
//
// Колбэк возвращает ЧИСЛО — отрицательное, ноль или положительное, — а не
// true/false. Булев колбэк не сортирует вообще: false → 0 («равны»), true → 1
// («больше»), а отрицательного «меньше» он не возвращает никогда.
const byBoolean = (a: number, b: number): number => Number(a > b);
console.log('булев колбэк:', [5, 4, 3, 2, 1].sort(byBoolean)); // [ 5, 4, 3, 2, 1 ] — не тронут

console.log('9)', ['ё', 'е', 'ж'].sort(), ['ё', 'е', 'ж'].sort((a, b) => a.localeCompare(b)));
// [ 'е', 'ж', 'ё' ] [ 'е', 'ё', 'ж' ]

// По умолчанию сортировка идёт по кодам символов, и «ё» уезжает в конец,
// потому что её код больше. localeCompare знает алфавит и ставит её на место.

