// ── Объявление и вызов ─────────────────────────────────────────────────────
// function greet         — объявить функцию с именем greet;
// (name: string)         — параметр: имя для того, что передадут при вызове;
// : string после скобок  — тип результата: функция обещает вернуть строку;
// return …               — отдать значение тому, кто вызвал, и сразу выйти;
// greet('Ann')           — вызов; 'Ann' — аргумент, он ляжет в параметр name.
// Тело выполняется при КАЖДОМ вызове, а не в момент объявления.
function greet(name: string): string {
  return `Привет, ${name}!`;
}
console.log('1)', greet('Ann'), greet('Bob')); // 1) Привет, Ann! Привет, Bob!

// ── Функция без return ─────────────────────────────────────────────────────
// Без return функция возвращает undefined — всегда. addNoReturn сумму
// посчитала и выбросила.
// : void — «полезного результата нет». Так помечают функции, которые что-то
// делают (печатают, кликают), а не считают. Если return нет, TypeScript
// поставит void сам. На деле всё равно приходит undefined.
function printSum(a: number, b: number): void {
  console.log('2) сумма:', a + b);
}
function addNoReturn(a: number, b: number) {
  a + b;
}
// 2) напечатается раньше 3): прежде чем печатать, console.log вычисляет все
// свои аргументы — и для этого вызывает printSum, а та печатает сразу.
console.log('3)', printSum(2, 3), addNoReturn(2, 3));
// 2) сумма: 5
// 3) undefined undefined

// Если тип результата обещан, а return нет, TypeScript не пропустит.
// Поэтому тип результата и пишут: он ловит забытый return.
// ❌ TS2355: A function whose declared type is neither 'undefined', 'void', nor 'any' must return a value.
// function sumTyped(a: number, b: number): number { a + b; }

// ── Три записи одной функции ───────────────────────────────────────────────
// Объявление (function declaration) — отдельная инструкция, у функции есть имя.
function addDeclared(a: number, b: number): number {
  return a + b;
}
// Функциональное выражение (function expression) — функция стоит справа
// от =, как любое значение. Имя здесь у переменной.
const addExpressed = function (a: number, b: number): number {
  return a + b;
};
// Стрелочная функция (arrow function) — то же выражение, короче.
const addArrow = (a: number, b: number): number => a + b;
console.log('4)', addDeclared(2, 3), addExpressed(2, 3), addArrow(2, 3)); // 4) 5 5 5

// Результат один. Различаются они в трёх местах, каждое — в своём примере:
// поднятие (04-scope.ts), свой arguments (02-parameters.ts), свой this (занятие 2).

// ── Тело стрелки: короткое и полное ────────────────────────────────────────
// Короткое тело — одно выражение после =>: его значение возвращается само.
// Полное тело — в фигурных скобках: там return пишут сами.
const sumShort = (a: number, b: number): number => a + b;
const sumLong = (a: number, b: number): number => {
  const total = a + b;
  return total;
};
// Чтобы вернуть объект коротким телом, его берут в круглые скобки. Без них
// фигурные скобки прочитаются как тело функции, и вернётся undefined.
const wrap = (n: number) => ({ value: n });
console.log('5)', sumShort(2, 3), sumLong(2, 3), wrap(5)); // 5) 5 5 { value: 5 }

// ── Анонимная функция и IIFE ───────────────────────────────────────────────
// function () {…} — анонимная функция, без имени. Стрелки анонимные всегда.
// (function () {…}) — скобки вокруг говорят «это выражение»: строка,
// начатая словом function, иначе была бы объявлением, и () после — ошибкой.
// (…)() — сразу вызвать то, что в скобках.
// Функция, которую создали и тут же вызвали, — IIFE (Immediately Invoked
// Function Expression, «выражение, вызванное сразу»). Зачем: у неё своя
// область видимости, hidden снаружи не видно. До let, const и модулей это
// был главный способ спрятать переменные. Сегодня пишут редко, а в старом
// коде и в чужих библиотеках встречается постоянно.
(function () {
  const hidden = 'видно только внутри';
  console.log('6)', hidden); // 6) видно только внутри
})();
(() => console.log('7) стрелка тоже вызывается сразу'))(); // 7) стрелка тоже вызывается сразу

// В product лежит не функция и не «запомненный вызов», а ЧИСЛО 42:
// стрелка вызвана один раз, прямо здесь, и её результат положен в переменную.
// Дальше product — обычное число, никакой функции при обращении не вызывается.
const product = ((a: number, b: number): number => a * b)(6, 7);
console.log('8)', product, typeof product, product * 2); // 8) 42 number 84

// Чаще всего анонимная функция живёт не так, а аргументом другой функции —
// колбэком (03-functions-as-values.ts).

