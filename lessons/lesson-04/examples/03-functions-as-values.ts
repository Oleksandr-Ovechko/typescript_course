// ── Без скобок — сама функция ──────────────────────────────────────────────
// Со скобками — ВЫЗОВ: выполнить тело и взять результат.
// Без скобок — САМА функция, такое же значение, как число или строка.
// Её можно положить в другую переменную: sayHello — та же функция
// под вторым именем, а не результат greet.
function greet(name: string): string {
  return `Привет, ${name}!`;
}
const sayHello = greet;
const greeting = greet('Kim');
console.log('1)', typeof greet, typeof sayHello, typeof greeting); // 1) function function string
console.log('2)', sayHello('Kim'), sayHello === greet); // 2) Привет, Kim! true

// ── Тип функции и сама функция ─────────────────────────────────────────────
// Обе записи — со стрелкой, но это разные вещи.
//   слева от =  : (x: number, y: number) => number   — ТИП: описание, какая
//                 функция здесь будет лежать: «от двух чисел, вернёт число».
//                 Он ничего не делает и в JavaScript не попадает вовсе.
//   справа от = : (x, y) => x * y                    — САМА функция: что делать.
// Типы x и y справа TypeScript берёт из описания слева.
const multiply: (x: number, y: number) => number = (x, y) => x * y;
console.log('3)', multiply(6, 7)); // 3) 42

// ── Колбэк ─────────────────────────────────────────────────────────────────
// Функция — значение, значение можно передать аргументом. Параметр
// operation описан ТИПОМ функции: «передадут функцию от двух чисел,
// которая вернёт число». Какую именно — решает тот, кто вызывает calculate.
// operation не нужно нигде объявлять: это имя параметра, как a и b.
function calculate(a: number, b: number, operation: (x: number, y: number) => number): number {
  return operation(a, b);
}
const addArrow = (x: number, y: number): number => x + y;
// Передаём функцию БЕЗ скобок. Мы ни разу не пишем multiply(…):
// вызывает её calculate — со своими a и b.
// Третий вызов — анонимная функция, созданная прямо на месте.
console.log('4)', calculate(6, 7, multiply), calculate(6, 7, addArrow), calculate(6, 7, (x, y) => x - y));
// 4) 42 13 -1

// Колбэк (callback) — функция, которую передают в другую функцию аргументом,
// чтобы та вызвала её сама. Пишете её вы, вызывает принимающая сторона.
// Так устроен каждый тест Playwright: test('название', async () => { … }) —
// второй аргумент колбэк, и вызывает его Playwright.
function repeatTimes(times: number, action: (round: number) => void): void {
  for (let round = 1; round <= times; round++) {
    action(round);
  }
}
repeatTimes(2, (round) => console.log('5) круг', round));
// 5) круг 1
// 5) круг 2

// ── Вызов вместо передачи ──────────────────────────────────────────────────
// multiply(6, 7) — это вызов. Он выполнится сразу, ещё до calculate,
// и calculate получит число 42 вместо функции.
//   передать — без скобок:  calculate(6, 7, multiply)
//   вызвать  — со скобками: multiply(6, 7)   → 42, а не функция
// ❌ TS2345: Argument of type 'number' is not assignable to parameter of type '(x: number, y: number) => number'.
// calculate(6, 7, multiply(6, 7));

// ── Рекурсия ───────────────────────────────────────────────────────────────
// Функция может вызвать любую функцию, которую видит, — и себя тоже.
// Рекурсия (recursion) — функция вызывает саму себя, каждый раз с задачей
// поменьше. Обязателен БАЗОВЫЙ СЛУЧАЙ — условие, при котором она себя
// больше не вызывает (здесь n <= 1).
//
//   factorial(3)
//     = 3 * factorial(2)
//             = 2 * factorial(1)
//                     = 1            ← базовый случай
//             = 2 * 1 = 2
//     = 3 * 2 = 6
//
// Вызовы складываются стопкой, пока не дойдут до базового случая, и потом
// сворачиваются обратно с ответами.
function factorial(n: number): number {
  if (n <= 1) {
    return 1;
  }
  return n * factorial(n - 1);
}
console.log('6)', factorial(1), factorial(3), factorial(5)); // 6) 1 6 120

// Без базового случая стопка растёт, пока не кончится место. Безопасно
// проверить в терминале — падает за доли секунды:
//   node -e "function down(n) { return down(n + 1); } down(0)"
//   RangeError: Maximum call stack size exceeded
// Это же сообщение будет в упавшем тесте, если функция случайно зовёт сама себя.

// ── Имя у функционального выражения ────────────────────────────────────────
// Выражение тоже может быть с именем: function tick(…). Это имя видно ТОЛЬКО
// внутри самой функции — чтобы вызвать себя. Снаружи её зовут countdown.
// Тернарник: условие ? значение-если-да : значение-если-нет (урок 3).
const countdown = function tick(n: number): string {
  return n === 0 ? 'старт' : `${n} ${tick(n - 1)}`;
};
console.log('7)', countdown(3)); // 7) 3 2 1 старт
// ❌ TS2304: Cannot find name 'tick'.
