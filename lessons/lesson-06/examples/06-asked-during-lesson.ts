// ── Функция, которая возвращает функцию ───────────────────────────────────
// Начнём с того, что вообще может стоять после return. Число может:
function giveNumber(): number {
  return 42;
}
console.log('1)', giveNumber());

// Строка может. Объект может. А функция? Функция — это тоже значение (урок 3),
// значит тоже может.
function giveFunction(): () => string {
  return () => 'я та самая возвращённая функция';
}

const received = giveFunction();     // здесь лежит ФУНКЦИЯ, а не строка
console.log('2)', typeof received);
console.log('3)', received());       // вот теперь строка

// Отсюда и ответ на вопрос «почему const выглядит как функция». Потому что
// в него положили функцию. `const` описывает не то, ЧТО лежит в переменной,
// а то, что переменную нельзя переприсвоить.

// ── Две пары скобок подряд ────────────────────────────────────────────────
// Скобки означают «вызови то, что слева от меня». Слева от вторых скобок стоит
// результат первого вызова — то есть функция. Значит, её тоже можно вызвать:
console.log('4)', giveFunction()());

// Это не хитрость и не ошибка — просто два вызова подряд, записанные в строку.
// Так же читается page.locator('...').click(): сначала отработало левое,
// потом вызвали то, что оно вернуло.

// А вот вызов, результат которого никуда не кладут:
giveFunction();

// Ошибкой это не считается: ни компилятор, ни линтер ничего не скажут.
// Функция отработала, вернула значение, значение выбросили. Смысл в таком
// вызове есть только если внутри что-то происходит — запрос, запись в файл,
// клик по странице.

// ── Теперь то же самое, но с переменной внутри ────────────────────────────
// Разница с giveFunction ровно одна: между объявлением и return появилась
// переменная. Этого хватает, чтобы получилось замыкание.
function makeCounter(): () => number {
  let count = 0;
  return () => {
    count += 1;
    return count;
  };
}

const counter = makeCounter();
console.log('5)', counter(), counter(), counter());

// ── А если у внешней функции есть параметр? ───────────────────────────────
// Спросили: если передавать начальное значение, оно ведь будет пересчитываться
// каждый раз заново? Нет. Параметр — такая же переменная окружения, как и count,
// и лежит он в том же самом месте.
function makeCounterFrom(start: number): () => number {
  return () => {
    start += 1;
    return start;
  };
}

const fromTen = makeCounterFrom(10);
const fromHundred = makeCounterFrom(100);

console.log('6)', fromTen(), fromTen(), fromTen());
console.log('7)', fromHundred());
console.log('8)', fromTen(), '← продолжил со своего, а не начал заново');

// makeCounterFrom(10) выполнилась ОДИН раз. В её окружении start стал 10,
// и дальше с ним работает возвращённая функция. Второй вызов makeCounterFrom
// завёл другое окружение, со своим start. Ничего не пересчитывается —
// начальное значение задаётся один раз, при создании.

// ── Зачем оборачивать один тест в describe ────────────────────────────────
// Прозвучал ответ «потому что afterEach отработает в любом случае, даже если
// тест упал». Первая половина верна, вторая из describe не следует.
//
// test.afterEach работает и на верхнем уровне файла, безо всякого describe,
// и после упавшего теста тоже. Проверено настоящим прогоном:
//
//   test.beforeEach(() => console.log('[файл] beforeEach'));
//   test.afterEach(() => console.log('[файл] afterEach — отработал'));
//
//   test('падающий тест без describe', () => {
//     console.log('[файл] тело теста');
//     expect(1).toBe(2);
//   });
//
//   [файл] beforeEach
//   [файл] тело теста
//   [файл] afterEach — отработал     ← отработал, describe не понадобился
//   1 failed
//
// Гарантию уборки даёт afterEach, а не describe. Настоящие причины обёртки
// другие, и их три:
//
//   1. Имя с номером TestRail вешается на группу, а не на каждый тест.
//   2. describe создаёт общее окружение — то самое замыкание из файла 03.
//      Без него `let widgetContext` пришлось бы объявлять в области модуля,
//      где его увидели бы и соседние файлы при сборке.
//   3. Единый скоуп для хуков: beforeEach/afterEach применяются к тестам
//      этой группы, а не ко всему файлу. Пока тест один — разницы нет,
//      появится второй — станет важно.
//
// И про try/finally внутри теста: он тоже сработает, но у него другой охват.
// finally уберёт за телом теста; afterEach уберёт ещё и за упавшим beforeEach,
// и за таймаутом самого теста, до которого тело просто не дошло.

