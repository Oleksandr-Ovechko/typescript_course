// ── Замыкание помнит место, где функция НАПИСАНА ──────────────────────────
// На занятии прозвучало «замыкание запоминает окружение, с которым функция
// была вызвана». Наоборот: окружение того места, где её создали.
//
// На примере со счётчиком разница не видна — там окружение и создаётся в момент
// вызова внешней функции. Видна она вот здесь:
let label = 'глобальная';

function makePrinter(): () => string {
  const label = 'внутренняя';
  return (): string => label;
}

const printer = makePrinter();          // СОЗДАНА здесь

function callSite(): void {
  const label = 'окружение вызова';     // ← printer её не увидит
  void label;
  console.log('1)', printer());
}
callSite();
void label;

