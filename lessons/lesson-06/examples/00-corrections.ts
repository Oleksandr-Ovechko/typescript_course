// ── beforeAll выполняется ПОСЛЕ сборки ────────────────────────────────────
// Прозвучало «beforeAll и afterAll выполняются на моменте, когда Playwright
// собирает тела describe, тогда же и прогоняются». На сборке идут только тела
// describe. beforeAll запускается уже в воркере, перед первым тестом.
//
// Верное следствие то же, что и было: ИМЯ теста вычисляется на сборке, поэтому
// значение из beforeAll в него не попадёт. Про сам beforeAll — см. настоящий
// вывод прогона в 03-closures-in-tests.ts. Там же видно, что файл спека
// загружается дважды: процессом сборки и воркером.

// ── «Замыкания одинаковые во всех языках» ─────────────────────────────────
// Прозвучало дважды: «существует вообще во всех языках, и специальной
// конструкции у него нет», «это всегда было и во всех языках программирования».
//
// В PHP — языке монолита — обе половины расходятся с фактом:
//
//   $label = 'до';
//   $read  = function () use ($label)  { return $label; };   // → до
//   $label = 'после';
//
//   $label2 = 'до';
//   $read2  = function () use (&$label2) { return $label2; }; // → после
//   $label2 = 'после';
//
// Во-первых, use — это и есть та самая специальная конструкция: захват надо
// перечислить руками. Во-вторых, по умолчанию PHP захватывает ЗНАЧЕНИЕ.
//
// То есть правило «захватывается переменная, а не значение» — правило
// JavaScript, а не свойство замыканий вообще. В том же примере JS печатает
// «после», PHP — «до».

// ── this в Java, C# и PHP ─────────────────────────────────────────────────
// Прозвучало «this внутри метода всегда ссылается на объект того класса, где
// этот метод написан». В PHP $this — это экземпляр времени выполнения, и он
// вполне может быть наследником:
//
//   class Base  { public $name = 'Base';  public function who() { return get_class($this); } }
//   class Child extends Base { public $name = 'Child'; }
//   (new Child())->who();     // Child, хотя метод написан в Base
//
// Нужный контраст другой и он сильнее: в PHP получатель уезжает ВМЕСТЕ
// с методом. [$c, 'who'] и Closure::fromCallable([$c, 'who']) тащат объект
// за собой, а в JavaScript то же самое действие даёт
// «Cannot read properties of undefined» (см. orphan в 04-this.ts).

// ── call и bind в проекте есть ────────────────────────────────────────────
// Прозвучало «в нашем проекте вообще нигде не вызываются». По origin/draft
// на момент урока (27.08.2026): .call( — 2 файла, .bind( — 1, .apply( — 0;
// к 22.10.2026 — 28, 5 и 5. Оба вида разобраны в 05-call-apply-bind.ts:
//
//   mpNote.show.bind(mpNote)   — метод оторвали от объекта, this вернули
//   setter.call(el, val)       — функцию одолжили у прототипа
//
// Заодно поправка к цифрам: тестов по несколько в одном файле не «парочка».
// Таких спеков десятки (на 22.10.2026 — около сотни), в одном их двенадцать. Именно к ним
// относится предупреждение про общее окружение describe.

// ── Опциональная цепочка ловит и null ─────────────────────────────────────
// Прозвучало «сначала смотрит, что параметр слева не является undefined».
// И null тоже. Заодно: конструкция называется опциональная цепочка —
// на занятии она осталась без имени.
type Closable = { close: () => string };

const closable: Closable = { close: (): string => 'закрыли' };
const findContext = (): Closable | null => null;      // ничего не нашли
const missing = findContext();

console.log('6)', closable.close(), '·', missing?.close(), '← не упало на null');

try {
  // а проверка ровно на undefined пропустила бы null дальше — и вот результат
  const value: unknown = missing;
  if (value !== undefined) (value as Closable).close();
} catch (error) {
  console.log('7) проверка только на undefined:', (error as Error).message);
}

