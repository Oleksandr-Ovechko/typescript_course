// ── Сборщик мусора не удаляет «тут же» ────────────────────────────────────
// Прозвучало: «удаляет объекты, как только на них не остаётся ни одной живой
// ссылки», «увидит, что на неё никто не ссылается, и тут же её удалит».
// Неточны оба слова — и «тут же», и «ссылок».
// Проверяется одной командой — здесь она отдельно, потому что нужен флаг
// --expose-gc: без него сборку не позвать руками, а сама она за такой
// короткий скрипт не успеет.
//
//   node --expose-gc -e "
//   const mb = () => Math.round(process.memoryUsage().heapUsed / 1048576);
//   let a = { big: new Array(3e6).fill(0) }, b = { big: new Array(3e6).fill(0) };
//   a.peer = b; b.peer = a;
//   console.log('1) объекты живы          :', mb(), 'МБ');
//   a = null; b = null;
//   console.log('2) сразу после обнуления :', mb(), 'МБ');
//   global.gc();
//   console.log('3) после сборки          :', mb(), 'МБ');
//   "
//
//   1) объекты живы          : 49 МБ
//   2) сразу после обнуления : 50 МБ     ← «тут же удалит»?
//   3) после сборки          : 4 МБ
//
// Строка 2 закрывает первое слово: память не освобождается в момент
// исчезновения ссылки, сборка идёт тогда, когда движок решит.
//
// Строка 3 закрывает второе. Объекты ссылались друг на друга по кругу —
// «живые ссылки» на них были, — и всё равно собрались. Значит, V8 ссылки
// не считает: он идёт от корней и оставляет всё, до чего дошёл.
//
// Для замыканий важно именно это: окружение живо, пока оно ДОСТИЖИМО. Отсюда
// и вывод про widgetContext — он висит не потому, что сборщик медленный,
// а потому, что до него есть путь.

