// ── Стрелка МЕТОДОМ ломает this, стрелка КОЛБЭКОМ спасает ─────────────────
// На занятии showList был назван стрелочной функцией. В примере он обычный
// метод, а стрелка — это колбэк внутри forEach. Разница не косметическая:
// стрелка на месте метода всё ломает.
//
//   node -e "const g={title:'Наша группа',students:['Даниил'],showList:()=>{g.students.forEach(s=>console.log(this?.title+': '+s))}};g.showList()"
//   undefined: Даниил
//
// node -e запускает код обычным нестрогим скриптом, там this — глобальный объект.
// В модуле тот же код без ?. падает: Cannot read properties of undefined.
//
// У стрелки нет своего this, а объект окружения не создаёт — брать его в методе
