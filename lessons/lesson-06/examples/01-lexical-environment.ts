/**
 * Урок 6 · Как функция находит переменную.
 *
 * Что здесь: лексическое окружение заводится на каждый вызов · два вызова —
 * два независимых окружения · цепочка окружений и поиск имени изнутри наружу ·
 * затенение · функция помнит место, где её написали, а не откуда вызвали.
 *
 *   node lessons/lesson-06/examples/01-lexical-environment.ts   запустить
 *   yarn typecheck                                              проверить типы
 *
 * Слова «замыкание» в этом файле нет ни разу. Оно появится в следующем —
 * и появится не как новое правило, а как следствие того, что здесь разобрано.
 */

const pause = (ms: number): Promise<void> => new Promise((resolve) => setTimeout(resolve, ms));

// ── Окружение заводится при каждом вызове ─────────────────────────────────
// Правило области видимости с урока 4 — «внутреннее видит внешнее, наоборот
// нельзя» — верное, но оно не отвечает на вопрос, ГДЕ переменная лежит.
// Отвечает лексическое окружение: служебный объект, который движок заводит
// при входе в функцию и кладёт туда все её переменные.
function greet(name: string): void {
  console.log('1)', `привет, ${name}`);
}
greet('Даниил');

// Посмотреть на это окружение нельзя: доступа к нему из кода нет, его не вывести
// в консоль. Но оно есть, и у него два важных свойства.
//
// Первое: оно принадлежит ВЫЗОВУ, а не функции. У самой функции окружения нет —
// пока её не вызвали, класть переменные некуда.
// Второе: вызвали десять раз — завели десять окружений, и они независимы.

// ── Два вызова — два окружения, и они не мешают друг другу ────────────────
// Проверяем задержкой: оба вызова уходят ждать одновременно, и к моменту
// печати оба параметра давно «прошли». Каждый печатает свой.
function greetLater(name: string): void {
  setTimeout(() => console.log('2)', `привет с задержкой, ${name}`), 20);
}
greetLater('Даниил');
greetLater('Сергей');
await pause(50);

// Ничего неожиданного — и в этом весь смысл. Так функции работают в любом
// языке: каждый вызов работает со своими параметрами. Неожиданное начнётся
// тогда, когда окружение переживёт свой вызов (следующий файл).

// ── Цепочка окружений: поиск идёт наружу ──────────────────────────────────
// Функции вложены друг в друга — значит, и окружения тоже. У каждого есть
// скрытая ссылка на то, внутри которого оно создано. Эти ссылки и есть цепочка.
const projectName = 'wl-e2e';                 // глобальное окружение модуля

function outerFunction(): void {
  const suite = 'widgets';                    // окружение вызова outerFunction

  function innerFunction(): void {
    const testCase = 'C157112';               // окружение вызова innerFunction
    console.log('3)', `${projectName} / ${suite} / ${testCase}`);
  }

  innerFunction();
}
outerFunction();

// Как innerFunction собрала эту строку — по шагам, и каждый шаг одинаковый:
//   testCase    — есть у себя, взяли, дальше не идём;
//   suite       — у себя нет → поднялись во внешнее → есть, взяли;
//   projectName — у себя нет → внешнее нет → глобальное есть, взяли.
//
// Поиск идёт изнутри наружу и останавливается на ПЕРВОМ совпадении.
// Отсюда и правило урока 4: цепочка ведёт только наружу, обратных ссылок в ней
// нет — поэтому внешнее никогда не видит внутреннее.

// ── Затенение: ближайшее имя выигрывает ───────────────────────────────────
// Спросили на занятии: а если переменную с тем же именем объявить внутри?
const environment = 'staging';

function readEnvironment(): void {
  const environment = 'production';           // своё, ближе — оно и победит
  console.log('4)', environment);
}
readEnvironment();
console.log('5)', environment, '← снаружи ничего не изменилось');

// Никакого отдельного правила здесь нет: это тот же поиск изнутри наружу.
// Нашли у себя — наружу не пошли. И наоборот: внешняя функция до внутреннего
// имени не доберётся никогда, оно умрёт вместе с вызовом.

// ── Функция помнит место, где написана, а не откуда вызвана ───────────────
// Последний кусок механизма — и самый важный. Одна и та же функция, вызванная
// из двух разных мест, ищет имена по цепочке ТОГО места, где её написали.
const label = 'глобальная метка';

function makePrinter(): () => void {
  const label = 'внутренняя метка';
  return (): void => console.log('6)', label);
}

const printer = makePrinter();                // создана внутри makePrinter

function callFromElsewhere(): void {
  const label = 'метка места вызова';         // ← её printer не увидит
  void label;
  printer();
}
callFromElsewhere();

// Печатает «внутренняя метка». Не «метка места вызова» и не «глобальная метка».
// Цепочка окружений выстраивается там, где функцию НАПИСАЛИ, и переезжает
// вместе с ней. Куда её потом передали и откуда вызвали — не важно.
//
// На доске: функция помнит место, где её написали, а не откуда вызвали.
// Из этого правила и из «окружение на каждый вызов» дальше выводится всё
// остальное — и выводится, а не заучивается.

export {};
