// ── Спред и деструктуризация — по разные стороны от = ──────────────────────
// СПРАВА от = (или в вызове) ... — спред (урок 4): раскладывает массив или
// объект в НОВЫЙ. Так делают поверхностную копию (урок 5).
// СЛЕВА от = { } или [ ] — деструктуризация: шаблон, который раскладывает
// готовый объект по переменным. Собирать переменные в объект она не умеет —
// это делает литерал { a, b } (короткая запись из урока 5).
const colors = ['red', 'green'];
const colorsCopy = [...colors, 'blue']; // спред: новый массив
const [firstColor] = colors; // деструктуризация: взять первый элемент
console.log('1)', colorsCopy, firstColor); // 1) [ 'red', 'green', 'blue' ] red

// ── Объект: по имени ───────────────────────────────────────────────────────
//   item: product         взять свойство item, положить в переменную product
//   count = 1             если count в объекте undefined — взять 1
//   note = 'без пометки'  то же для note
//   ...restOfOrder        всё, что НЕ взяли по имени, — новым объектом
const order: { item: string; count?: number; note?: string | null; price: number } = {
  item: 'чай',
  note: null,
  price: 40,
};
const { item: product, count = 1, note = 'без пометки', ...restOfOrder } = order;
console.log('2)', product, count, note, restOfOrder); // 2) чай 1 null { price: 40 }

// Почему note — null, а не 'без пометки': умолчание срабатывает ТОЛЬКО на
// undefined, как у параметра функции (урок 4). null — это значение, его взяли
// как есть. count в заказе нет совсем — он undefined, и умолчание сработало.
// Порядок имён в шаблоне ни на что не влияет: «позже — перезаписалось» здесь
// не бывает.
//
// В restOfOrder нет ни item, ни note: остаток собирает только то, что
// не названо в шаблоне. Остался один price.
//
// item: product заводит ТОЛЬКО product. Переменной item не появилось:
// ❌ TS2304: Cannot find name 'item'.
// console.log(item);

// Нужно одно свойство — берём одно, остальные писать не нужно:
const { price } = order;
console.log('3)', price); // 3) 40

// Умолчание на undefined и на null — рядом:
const noNote: { note?: string | null } = {};
const nullNote: { note?: string | null } = { note: null };
const { note: missing = 'без пометки' } = noNote;
const { note: empty = 'без пометки' } = nullNote;
console.log('4)', missing, '|', empty); // 4) без пометки | null

// ── Двоеточие в шаблоне — не тип ───────────────────────────────────────────
// { item: string } слева от = не проверяет тип, а заводит переменную
// с именем string. TypeScript не возразит. Тип пишут ПОСЛЕ всего шаблона:
// const { item }: { item: string } = order.
const { item: string } = order;
console.log('5)', string); // 5) чай

// ── Массив — по позиции ────────────────────────────────────────────────────
// У элементов массива имён нет, поэтому шаблон берёт их по порядку. Имена
// переменных — любые. Пустое место между запятыми пропускает элемент.
// ...others — остальные элементы новым массивом, только последним.
const podium = ['Ann', 'Bob', 'Kate', 'Max'];
const [winner, , third, ...others] = podium;
console.log('6)', winner, third, others); // 6) Ann Kate [ 'Max' ]

// Перечислять все элементы не нужно: хвост можно просто не писать.
// Пропускать запятыми приходится только то, что стоит ДО нужного.
const [gold] = podium;
const [, , bronze] = podium;
console.log('7)', gold, bronze); // 7) Ann Kate

// ── Объект-параметр функции ────────────────────────────────────────────────
// Вместо имени параметра — шаблон: аргумент-объект разобран сразу.
// Поля именованные, порядок не важен, необязательное можно не передавать.
// Тип — после шаблона.
function formatPrice({ amount, currency = 'грн' }: { amount: number; currency?: string }): string {
  return `${amount} ${currency}`;
}
console.log('8)', formatPrice({ amount: 120 }), '|', formatPrice({ currency: '$', amount: 5 }));
// 8) 120 грн | 5 $

