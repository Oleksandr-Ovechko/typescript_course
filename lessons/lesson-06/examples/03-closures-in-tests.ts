// ── `let` в теле describe — это замыкание ─────────────────────────────────
// Вот настоящий спек проекта, projects/widgets/end-to-end-tests/event-widget/
// C157112.spec.ts, сокращённый до сути:
//
//   test.describe('[C157112][Event Widget]: Booking Non-integrated Event', () => {
//     let widgetContext: BrowserContext | undefined;
//
//     test.beforeEach(async ({ page }) => { ... });
//
//     test.afterEach(async ({ page }) => {
//       await widgetContext?.close();
//       ...
//     });
//
//     test('Client books non-integrated virtual event', async ({ page, browser }) => {
//       widgetContext = await browser.newContext();
//       ...
//     });
//   });
//
// Три функции: колбэк describe, колбэк afterEach, колбэк теста. Переменную
// widgetContext не объявляла ни одна из них — она лежит в окружении вызова
// колбэка describe, то есть во внешнем для всех троих. Каждый из них помнит
// место, где написан (правило 2.4), и поиск имени ведёт по этой цепочке.
//
// Поэтому afterEach видит то, что положил тест: смотрят они в одно и то же
// окружение. Аргументов между тестом и хуком не ходит, поэтому в проекте так
// и делают — через общую переменную describe. Способ без замыкания тоже есть:
// фикстура Playwright, которая и отдаёт значение тесту, и убирает его после
// (helpers/fixtures/test.ts, фикстура tracker).
//
// Таких файлов в проекте сотни, из них около девяноста — именно
// с `let widgetContext` (на 22.10.2026).

// ── Общая переменная между хуками ─────────────────────────────────────────
// То же самое на модели, которую можно запустить. Три функции, одна переменная,
// которую ни одна из них не объявляла.
let bookingMade = false;

function testBody(): void {
  bookingMade = true;
  console.log('2) тело теста: забронировали');
}

function afterEach(): void {
  console.log('3) afterEach видит bookingMade =', bookingMade);
  bookingMade = false;
  console.log('4) afterEach сбросил флаг');
}

console.log('1) до теста bookingMade =', bookingMade);
testBody();
afterEach();
console.log('5) после afterEach bookingMade =', bookingMade);

// Здесь всё в порядке ровно потому, что кто-то сбрасывает флаг. Уберите строку
// со сбросом — и второй тест в этом файле стартует с bookingMade === true,
// то есть увидит следы первого.
//
// Это и есть типовое «падает только при полном прогоне»: поодиночке зелено,
// целиком — красно. Окружение describe одно на все тесты файла.

// ── Тело describe выполняется раньше тестов ───────────────────────────────
// Playwright сначала выполняет тела всех describe, чтобы узнать, какие тесты
// есть в файле, и только потом запускает сами тесты. Это два разных момента
// времени, и замыкание живёт через оба.
const collected: Array<() => void> = [];

function describe(name: string, body: () => void): void {
  console.log('6) собираем:', name);
  body();
}

function testCase(name: string, body: () => void): void {
  collected.push(() => {
    console.log('   выполняем:', name);
    body();
  });
}

let widgetName: string | undefined;

describe('[C000000] пример', () => {
  console.log('7) тело describe: widgetName =', widgetName);
  testCase(`проверяем ${widgetName}`, () => console.log('9) внутри теста: widgetName =', widgetName));
});

widgetName = 'schedule';
console.log('8) запускаем собранное:');
for (const run of collected) run();

// Смотрите на две последние строки: одна и та же переменная, два разных ответа.
//
// Имя теста — «проверяем undefined» — это обычный шаблонный литерал. Он подставил
// значение прямо в момент вызова testCase, то есть на сборке, когда в widgetName
// ещё лежало undefined. Строку читают сразу.
//
// Тело теста — функция. Она ничего не вычисляет при создании, она замкнулась
// на переменную (файл 02) и заглянет в неё, когда её вызовут. Функцию читают
// потом, и к тому моменту там уже 'schedule'.
//
// Практическое следствие: значение, полученное в beforeAll, нельзя использовать
// в ИМЕНИ теста — имя вычисляется на сборке, значения там ещё нет.
//
//   test.describe('...', () => {
//     let skinName: string;
//     test.beforeAll(async () => { skinName = await createSkin(); });
//
//     test(`проверяем ${skinName}`, ...);                        // ← undefined в имени
//     test('проверяем', async () => { await open(skinName); });  // ← работает
//   });
//
// ⚠️ Сам beforeAll на сборке НЕ выполняется — он запускается уже в воркере,
// перед первым тестом. На сборке идут только тела describe. Вот настоящий
// вывод Playwright 1.60.0 с одним воркером:
//
//   A) файл загружен                     ← процесс сборки
//   B) тело describe. value = undefined
//   C) конец файла
//
//   Running 1 test using 1 worker
//
//   A) файл загружен                     ← воркер загружает файл ЗАНОВО
//   B) тело describe. value = undefined
//   C) конец файла
//   D) beforeAll. value = undefined      ← только теперь
//   F) тело теста. value = из beforeAll
//   ✓ E) имя теста: value = undefined
//
// Из этого вывода видно ещё одну вещь, о которой легко не знать годами: файл
// спека загружается ДВАЖДЫ — один раз процессом сборки, второй раз воркером.
// Всё, что написано в теле файла вне тестов, выполняется два раза.

// ── Чем замыкания опасны ──────────────────────────────────────────────────
// Три пункта, и каждый следует из механизма, а не запоминается отдельно.
//
//   1. Замыкание держит окружение достижимым — значит, держит в памяти всё,
//      что в нём лежит. widgetContext — это открытый браузер. Забыли close() —
//      он висит до конца прогона, а не до конца теста. Таких файлов около девяноста.
//
//   2. Окружение describe одно на все тесты файла. Тестов в файле может быть
//      больше одного: в проекте десятки таких спеков, в одном их двенадцать. Если два
//      теста пишут в одну переменную — они мешают друг другу.
//
//   3. Правило одно: если переменную видит больше одного колбэка — спросить,
//      кто и когда её сбрасывает. Не «кто читает», а именно кто сбрасывает.

