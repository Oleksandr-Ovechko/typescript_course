/**
 * Урок 6 · Замыкание.
 *
 * Что здесь: почему переменная жива после того, как функция закончилась ·
 * счётчик, который помнит своё значение · захватывается переменная, а не
 * значение · два вызова — два независимых замыкания.
 *
 *   node lessons/lesson-06/examples/02-closure.ts   запустить
 *   yarn typecheck                                  проверить типы
 *
 * Новых механизмов здесь нет. Всё выводится из двух правил предыдущего файла:
 * окружение заводится на каждый вызов + функция помнит место, где написана.
 */

// ── Внешняя функция закончилась. Почему переменная жива? ──────────────────
// Обычно переменные функции исчезают вместе с её вызовом: вызов закончился,
// окружение больше никому не нужно, движок его убирает. Но не здесь.
function makeGreeter(name: string): () => string {
  const greeting = `привет, ${name}`;         // живёт в окружении вызова makeGreeter
  return (): string => greeting;              // а эта функция уезжает наружу
}

const greetDaniil = makeGreeter('Даниил');    // makeGreeter отработала и закончилась
console.log('1)', greetDaniil());             // а greeting всё ещё на месте

// Почему: возвращённая функция помнит место, где её написали (правило 2.4),
// то есть держит ссылку на окружение вызова makeGreeter. Пока жива она — живо
// и окружение. Убрать его движок не может: оно ещё достижимо.
//
// Это и есть замыкание. Отдельной конструкции для него в языке нет —
// специального синтаксиса не существует, оно получается само.

// ── Про сборщик мусора, аккуратно ─────────────────────────────────────────
// Формулировка «сборщик удаляет объект, как только на него не осталось ссылок»
// — неточная, и обе неточности важны.
//
//   1. Не «как только». Сборка идёт не в момент исчезновения ссылки, а тогда,
//      когда движок решит. Память освобождается позже, иногда сильно позже.
//   2. Не «ссылок». V8 не считает ссылки — он идёт от корней и оставляет всё,
//      до чего дошёл. Поэтому два объекта, ссылающиеся друг на друга по кругу,
//      прекрасно собираются: ссылки есть, а достижимости нет.
//
// Для замыканий важно именно второе слово: окружение живо, пока оно
// ДОСТИЖИМО. Живая функция — путь к нему, значит оно останется.

// ── Счётчик: замыкание, которое ещё и меняет переменную ───────────────────
function makeCounter(): () => number {
  let count = 0;                              // одна переменная на все вызовы
  return (): number => {
    count += 1;
    return count;
  };
}

const firstCounter = makeCounter();
const secondCounter = makeCounter();

console.log('2)', firstCounter(), firstCounter(), firstCounter());
console.log('3)', secondCounter());
console.log('4)', firstCounter(), '← первый счётчик продолжил со своего места');

// Печатает 1 2 3, потом 1, потом 4 — а не 1 2 3 4.
// Два вызова makeCounter завели ДВА окружения, в каждом свой count. Правило
// «окружение на каждый вызов» никуда не делось, просто теперь его видно.
//
// Обратите внимание, что count здесь снаружи не достать никак: имени нет,
// доступ только через возвращённую функцию. Так делают приватные данные.

// ── Захватывается переменная, а не значение ───────────────────────────────
// Самый важный пункт урока и единственное место, где интуиция подводит всех.
let captured = 'до';
const readCaptured = (): string => captured;  // функция создана сейчас
captured = 'после';                           // переменную поменяли потом

console.log('5)', readCaptured());

// Печатает «после», а не «до».
//
// Замыкание держит САМУ переменную, а не снимок её значения на момент создания.
// Читает её тогда, когда функцию вызвали, — а к этому моменту там уже «после».
//
// Это не противоречит поиску изнутри наружу: captured лежит в одном-единственном
// глобальном окружении, и функция смотрит именно в него. Чтобы напечаталось
// «до», значение надо изолировать — например, передать параметром:
captured = 'снимок';
const readCopy = ((snapshot: string) => (): string => snapshot)(captured);
captured = 'изменили после снимка';
console.log('6)', readCopy(), '← параметр скопировал значение, дальше не следит');
console.log('7)', readCaptured(), '← а этот по-прежнему следит за переменной');

// ⚠️ Это правило JavaScript, а не свойство замыканий вообще. В PHP — языке
// монолита — по умолчанию наоборот, захватывается значение, и переменные
// захвата надо перечислить руками:
//
//   $label = 'до';
//   $read  = function () use ($label)  { return $label; };  // → до
//   $read2 = function () use (&$label) { return $label; };  // → после
//
// Так что «замыкания везде одинаковые» — неправда. Одинакова идея, детали
// расходятся, и расходятся ровно в том месте, которое здесь главное.

// ── Два замыкания — два окружения ─────────────────────────────────────────
// То же самое, но с двух ракурсов сразу: и счётчик свой, и параметр свой.
function makeLogger(prefix: string): (message: string) => string {
  let calls = 0;
  return (message: string): string => {
    calls += 1;
    return `[${prefix} #${calls}] ${message}`;
  };
}

const widgetsLog = makeLogger('widgets');
const monolithLog = makeLogger('monolith');

console.log('8)', widgetsLog('открыли'));
console.log('9)', monolithLog('вошли'));
console.log('10)', widgetsLog('закрыли'), '← счётчик виджетов свой, он уже на двойке');

// Захвачен не только calls, но и prefix: параметры лежат в том же окружении
// вызова, что и объявленные внутри переменные. Никакой разницы между ними нет.
//
// Эта конструкция — «функция-шаблон, из которой делают настроенные функции» —
// одна из самых частых в библиотеках. И ровно на ней устроен bind (файл 05).

