// ── Баг 1. Сумма со страницы ───────────────────────────────────────────────
// Цена пришла со страницы строкой. Сумма с доставкой должна быть 15.5.
const pageTotal = '12.50';
const delivery = 3;
const total: number = pageTotal + delivery;

// ── Баг 2. Разделители разрядов ────────────────────────────────────────────
// Из суммы нужно убрать все запятые: '1,234,567' → '1234567'.
const rawAmount = '1,234,567';
const cleanAmount = rawAmount.replace(',', '');

// ── Баг 3. Итог с налогом для отчёта ───────────────────────────────────────
// В отчёт нужна строка с двумя знаками после точки: 19.999 + налог 2 → '22.00'.
const subtotal = 19.999;
const tax = 2;
const shownWithTax = subtotal.toFixed(2) + tax;

// ── Баг 4. Цена товара ─────────────────────────────────────────────────────
// Цена со страницы — '19.99'. Нужна как число, без потерь: 19.99.
const priceText = '19.99';
const price = parseInt(priceText);

// ───────────────────────────────────────────────────────────────────────────
// Ниже ничего не меняем: это проверки. Каждая должна напечатать true.
// ───────────────────────────────────────────────────────────────────────────

console.log('1)', total === 15.5, total);
console.log('2)', cleanAmount === '1234567', cleanAmount);
console.log('3)', shownWithTax === '22.00', shownWithTax);
console.log('4)', price === 19.99, price);

