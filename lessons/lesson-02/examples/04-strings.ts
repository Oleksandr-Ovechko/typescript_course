// ── Методы строки ничего в ней не меняют ───────────────────────────────────
// trim() убирает пробелы, табуляции и переносы строк по краям.
const rawName = '  Ann  ';
const trimmedName = rawName.trim();
rawName.trim(); // отдельной строкой не делает НИЧЕГО — результат выброшен
console.log('1)', `[${rawName}]`, `[${trimmedName}]`); // 1) [  Ann  ] [Ann]
// Каждый метод строки отдаёт НОВУЮ строку. Результат нужно положить под имя.

// ── Регистр и язык ─────────────────────────────────────────────────────────
// toUpperCase знает любой алфавит, не только английский.
console.log('2)', 'привет'.toUpperCase(), 'ann'.toLowerCase()); // 2) ПРИВЕТ ann

// Правила некоторых языков отличаются: в турецком у строчной i заглавная —
// İ, с точкой. toLocaleUpperCase с кодом языка это учитывает.
console.log('3)', 'i'.toUpperCase(), 'i'.toLocaleUpperCase('tr')); // 3) I İ
// Без кода языка toLocaleUpperCase берёт язык системы — на разных машинах
// результат может быть разным. Поэтому язык указывают явно.

// ── replace заменяет только первое ─────────────────────────────────────────
const amount = '1,234,567';
console.log('4)', amount.replace(',', ''), amount.replaceAll(',', '')); // 4) 1234,567 1234567
// Нужно заменить все — replaceAll. В чужом коде чаще встретится
// replace(/,/g, '') — регулярное выражение с флагом g, «все совпадения»
// (регулярки — урок 13).

// ── .length считает ячейки, а не буквы ─────────────────────────────────────
// .length — без скобок: это не действие, а данные, как client.name.
// Строка в памяти — ряд ячеек. Почти любой символ — одна ячейка: латиница,
// кириллица, иероглиф. Эмодзи — две и больше.
console.log('5)', 'Ann'.length, 'привет'.length, '中'.length, '👍'.length); // 5) 3 6 1 2
// Это не байты: в файле 'привет' занимает 12 байт, а .length — 6.
// У массива .length — число элементов: [10, 20, 30].length — 3.

// ── slice: конец не включается ─────────────────────────────────────────────
// slice(0, 3) — с ячейки 0 до ячейки 3, саму ячейку 3 не берёт.
console.log('6)', 'привет'.slice(0, 3), '中文'.slice(0, 1), '👍'.slice(0, 1)); // 6) при 中 �
// Иероглиф — одна ячейка, отрезается целым. Эмодзи — две, slice(0, 1)
// отрезал половину. Обрезая текст со страницы по .length, можно разрезать символ.
// (splice — метод массива, а не строки: у строки его нет.)

