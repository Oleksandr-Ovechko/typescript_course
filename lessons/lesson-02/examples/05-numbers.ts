// ── Дробные числа ──────────────────────────────────────────────────────────
console.log('1)', 0.1 + 0.2, 0.1 + 0.2 === 0.3); // 1) 0.30000000000000004 false
console.log('2)', 0.5 + 0.25, 0.5 + 0.25 === 0.75); // 2) 0.75 true

// Число хранится в двоичной записи. 0.5 = 1/2 и 0.25 = 1/4 в ней короткие
// и хранятся точно. 0.1 и 0.2 в двоичной — бесконечные дроби, как 1/3
// в десятичной (0.333…). Их обрезают, и погрешность всплывает при сложении.
//
// Так хранят дробные почти все языки, и сумма у них та же самая: Python
// тоже печатает 0.30000000000000004. Языки различаются только тем, сколько
// знаков показывают при печати по умолчанию.
//
// Правило: дробные не сравнивают через ===. В тестах для этого есть
// toBeCloseTo (урок 15): он проверяет, что разница меньше половины
// последнего знака, по умолчанию — меньше 0.005.

// ── NaN ────────────────────────────────────────────────────────────────────
// NaN — «не число» (Not a Number): результат неудачного превращения или
// неудачной арифметики. По typeof — number: NaN — особое значение внутри
// числового типа, так устроены дробные числа во всех языках.
const notNumber = Number('двенадцать');
console.log('3)', notNumber, typeof notNumber, notNumber === notNumber); // 3) NaN number false
console.log('4)', Number.isNaN(notNumber), Boolean(notNumber)); // 4) true false
// NaN — единственное значение, не равное самому себе: x === NaN всегда
// ложь. Проверяют Number.isNaN(x) — это метод встроенного объекта Number,
// у самого числа его нет. NaN — восьмое ложное значение.

// ── Number, parseInt, parseFloat ───────────────────────────────────────────
console.log('5)', Number('12.5'), Number('12.5 USD'), Number(''), Number('  7 ')); // 5) 12.5 NaN 0 7
console.log('6)', parseInt('12.5 USD'), parseFloat('12.5 USD'), parseFloat('')); // 6) 12 12.5 NaN

// Number(s)     — вся строка должна быть числом, иначе NaN; пробелы и
//                 переносы по краям прощает. Пустая строка — 0!
// parseFloat(s) — читает слева, пока читается, с дробной частью.
// parseInt(s)   — читает слева, пока читается, только целое.
//
// Две ловушки:
// - Number('') — ноль. Пустая ячейка молча станет 0, и сумма сойдётся,
//   хотя данных не было.
// - parseInt теряет копейки: parseInt('12.5') — 12. Для денег —
//   parseFloat или Number, не parseInt.

// Пустую ячейку часто заменяют нулём через ||:
console.log('7)', parseFloat('') || 0); // 7) 0
// Тест перестаёт падать на NaN. Но цена: «ячейка пустая» и «в ячейке 0»
// становятся неразличимы. Если пустая ячейка — это баг, лучше, чтобы
// тест упал, чем молча считал её нулём.

// ── toFixed отдаёт строку ──────────────────────────────────────────────────
const orderTotal = 19.999;
const shownTotal = orderTotal.toFixed(2);
console.log('8)', shownTotal, typeof shownTotal); // 8) 20.00 string
console.log('9)', shownTotal + 1, Number(shownTotal) + 1); // 9) 20.001 21
console.log('10)', (1.005).toFixed(2), (25).toFixed(2)); // 10) 1.00 25.00

// toFixed отдаёт строку: '20.00' + 1 — склейка. Он округляет то, что
// хранится в памяти, а 1.005 в двоичной хранится чуть меньше 1.005, —
// поэтому '1.00', а не '1.01'. (25).toFixed — в скобках, потому что точку
// сразу после цифр язык читает как начало дробной части.
//
// toFixed — для вывода: последним шагом, когда число превращается в текст
// для поля или отчёта. Считают — числами.

// ── Округление через Math ──────────────────────────────────────────────────
// Math — встроенный объект с математикой. Его методы отдают число, а не
// строку, и лишних нулей не добавляют. Округляют до целого.
console.log('11)', Math.ceil(19.01), Math.floor(19.99), Math.round(19.5)); // 11) 20 19 20
// ceil — вверх, floor — вниз, round — к ближайшему; ровно посередине —
// вверх, и у отрицательных тоже: Math.round(-2.5) — -2.

// Округлить до центов «умножить, округлить, разделить» — та же ловушка,
// что у toFixed: 1.005 * 100 — это 100.49999999999999.
console.log('12)', 1.005 * 100, Math.round(1.005 * 100) / 100); // 12) 100.49999999999999 1

