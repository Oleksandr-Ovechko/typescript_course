/**
 * Урок 2 · Значение и имя для него.
 *
 * Что здесь: `console.log` с несколькими значениями · `const` и `let` ·
 * аннотация `: string` · строка в обратных кавычках.
 *
 *   node lessons/lesson-02/examples/01-values-and-names.ts   запустить
 *   yarn typecheck                                           проверить типы
 */

// ── console.log ────────────────────────────────────────────────────────────
// Всё, что в скобках через запятую, печатается через пробел в одну строку.
// Строки — без кавычек. '1)' в начале — обычная строка-метка.
console.log('1)', 'Ann', 42, true); // 1) Ann 42 true

// ── const и let ────────────────────────────────────────────────────────────
// `=` — не «равно», а «положить значение справа под имя слева».
const clientName = 'Ann';
let visitCount = 3;
visitCount = 4; // без const/let — заменить то, что уже лежит под именем
console.log('2)', clientName, visitCount); // 2) Ann 4

// const — значение положили один раз, заменить нельзя.
// ❌ TS2588: Cannot assign to 'clientName' because it is a constant.
// clientName = 'Bob';

// По умолчанию пишут const, let — только когда значение правда меняется:
// видишь const — знаешь, что ниже по коду значение то же самое.
// Третий способ, var, — старый; почему его не пишут — урок 3.

// ── Аннотация : string ─────────────────────────────────────────────────────
// `: тип` после имени — обещание, какие значения будут под этим именем.
// node при запуске аннотации выбрасывает, проверяет их только yarn typecheck.
const city: string = 'Kyiv';
const spotsLeft: number = 12;
console.log('3)', city, spotsLeft); // 3) Kyiv 12

// Если пообещать число, а положить строку, node всё равно выполнит файл,
// а yarn typecheck откажется:
// ❌ TS2322: Type 'string' is not assignable to type 'number'.
// const spotsBroken: number = 'двенадцать';

// ── Строка в обратных кавычках ─────────────────────────────────────────────
// Внутри `…` конструкция ${…} подставляет значение. Внутри ${} может быть
// любое выражение: сначала посчитается, потом подставится. Считается это
// при выполнении, на той строке, где стоит.
const greeting = `Клиент ${clientName}, визитов: ${visitCount}`;
console.log('4)', greeting); // 4) Клиент Ann, визитов: 4
console.log('5)', `мест: ${spotsLeft - 2}`); // 5) мест: 10

// В обычных кавычках подстановки нет — ${ останется просто символами.
console.log('6)', 'мест: ${spotsLeft}'); // 6) мест: ${spotsLeft}

