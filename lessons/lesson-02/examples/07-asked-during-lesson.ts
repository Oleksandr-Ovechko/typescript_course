// ─────────────────────────────────────────────────────────────────────────────
// 1. Шаблонные литералы (template literals)
// ─────────────────────────────────────────────────────────────────────────────
// Строку в JS можно объявить тремя способами. Первые два — обычные кавычки,
// одинарные и двойные, разницы между ними нет:

const single = 'обычная строка';
const double = "тоже обычная, кавычки другие";
const inside = "внутри двойных можно писать 'одинарные' без экранирования";
console.log('1)', single, '|', double, '|', inside);

// Третий способ — обратные кавычки (backticks, клавиша под Esc). Внутри них
// работает подстановка: `${ выражение }`.

const userName = 'Ann';
const visits = 3;
console.log('1)', `Клиент ${userName}, визитов: ${visits}`);

// Без них пришлось бы склеивать плюсом — и чем больше переменных, тем хуже:
console.log('1)', 'Клиент ' + userName + ', визитов: ' + visits);

// Подстановка происходит НЕ на этапе компиляции, а В РАНТАЙМЕ,
// каждый раз заново при вычислении строки. Доказательство — счётчик,
// который меняется между двумя вызовами:

let counter = 0;
function bump(): number {
  counter += 1;
  return counter;
}
const label = (): string => `вызов №${bump()}`;
console.log('1)', label()); // вызов №1
console.log('1)', label()); // вызов №2  ← будь это compile-time, было бы одно и то же

// И если скомпилировать файл через tsc, в выходном .js шаблонный литерал
// останется ровно таким же — компилятор его не трогает:
//   npx tsc lessons/lesson-02/examples/07-asked-during-lesson.ts \
//       --outDir /tmp/demo --target ES2022 --module ESNext

// Внутри `${}` можно любое выражение, и результат всегда приводится к строке.
// Отсюда фокус с урока: подставили функцию без вызова — получили её исходник.
// Пробелы после `bump()` — место, где был `: number`: Node при запуске заменил
// аннотацию пробелами той же длины (см. «Типов в рантайме нет» в конспекте).
console.log('1)', `функция целиком: ${bump}`);
console.log('1)', `а так — её результат: ${bump()}`);

// ─────────────────────────────────────────────────────────────────────────────
// 2. Тернарный оператор
// ─────────────────────────────────────────────────────────────────────────────
// Сокращённая запись if/else, которая ВОЗВРАЩАЕТ значение:
//
//   условие ? значение_если_true : значение_если_false

const spots = 0;
const short = spots > 0 ? 'есть места' : 'мест нет';
console.log('2)', short);

// Развёрнутый эквивалент — обратите внимание, тут нужна отдельная переменная
// и четыре строки вместо одной:
let long: string;
if (spots > 0) {
  long = 'есть места';
} else {
  long = 'мест нет';
}
console.log('2)', long);

// Именно поэтому тернарник удобен внутри выражений — там, где `if` вообще
// нельзя поставить. Например, прямо в аргументе console.log (пример 05, catch):
try {
  JSON.parse('{');
} catch (error) {
  console.log('2)', error instanceof Error ? error.message : 'не Error');
}

// Правило: тернарник хорош, пока помещается в строку и не вложен в другой
// тернарник. Три вложенных подряд — верный признак, что нужен switch.

// ─────────────────────────────────────────────────────────────────────────────
// 3. switch/case против цепочки if/else
// ─────────────────────────────────────────────────────────────────────────────
type Channel = 'mail' | 'sms' | 'push';

function selectorViaIf(channel: Channel): string {
  if (channel === 'mail') {
    return 'input.js-channel-mail';
  } else if (channel === 'sms') {
    return 'input.js-channel-sms';
  } else if (channel === 'push') {
    return 'input.js-channel-push';
  }
  return 'неизвестный канал';
}

function selectorViaSwitch(channel: Channel): string {
  switch (channel) {
    case 'mail':
      return 'input.js-channel-mail';
    case 'sms':
      return 'input.js-channel-sms';
    case 'push':
      return 'input.js-channel-push';
    default:
      return 'неизвестный канал';
  }
}
console.log('3)', selectorViaIf('sms'), '===', selectorViaSwitch('sms'));

// Обе записи равнозначны. switch читается лучше, когда сравнивается ОДНА
// переменная с набором конкретных значений, и его `default` явно показывает
// ветку «ничего не подошло». Плюс именно в switch удобно ставить проверку
// полноты через never — см. пример 05.
//
// Две ловушки switch, которых нет у if:
//   1. сравнение всегда строгое (===), привести типы он не будет;
//   2. без `return` или `break` выполнение «проваливается» в следующий case.

function fallthroughDemo(n: number): string {
  const log: string[] = [];
  switch (n) {
    case 1:
      log.push('единица');
    // ← нет break: провалились дальше
    case 2:
      log.push('двойка');
      break;
    case 3:
      log.push('тройка');
      break;
    default:
      log.push('что-то ещё');
  }
  return log.join(' + ');
}
console.log('3) провал без break:', fallthroughDemo(1)); // единица + двойка
console.log('3) с break:', fallthroughDemo(2)); // двойка

// ─────────────────────────────────────────────────────────────────────────────
// 4. Методы объекта
// ─────────────────────────────────────────────────────────────────────────────
// Функция, лежащая внутри объекта, называется методом. В типе она описывается
// так же, как обычное поле: `имя: (параметры) => возвращаемыйТип`.

type Inventory = {
  id: string;
  checkItem: (itemId: string) => boolean;
};

const inventory: Inventory = {
  id: 'INV-1',
  // тип параметра писать не нужно — TS берёт его из типа поля
  checkItem: (itemId) => itemId === '123',
};
console.log('4)', inventory.checkItem('123'), inventory.checkItem('999'));

// Есть вторая форма записи типа — «сигнатура метода». Работает так же:
type Inventory2 = {
  id: string;
  checkItem(itemId: string): boolean;
};
const inventory2: Inventory2 = {
  id: 'INV-2',
  // а в самом объекте это короткая запись метода, без `: (...) =>`
  checkItem(itemId) {
    return itemId.startsWith('OK');
  },
};
console.log('4)', inventory2.checkItem('OK-1'), inventory2.checkItem('NO'));

// ─────────────────────────────────────────────────────────────────────────────
// 5. Дефолтные значения параметров
// ─────────────────────────────────────────────────────────────────────────────
// `= значение` после параметра означает «если аргумент не передали, взять это».
// Это обычный JavaScript, к типам отношения не имеет.

function greet(name: string, greeting = 'Привет'): string {
  return `${greeting}, ${name}!`;
}
console.log('5)', greet('Ann'));
console.log('5)', greet('Bob', 'Здравствуйте'));

// Ровно поэтому в примере 04 у `generateClientData` стоит `= {}` — чтобы
// функцию можно было вызвать вообще без аргументов.
//
// Ловушка: дефолт срабатывает только на `undefined`, но не на `null`:
console.log('5) undefined →', greet('Ann', undefined));
console.log('5) null →', greet('Ann', null as unknown as string));

