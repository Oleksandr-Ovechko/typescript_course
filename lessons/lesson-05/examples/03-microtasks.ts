/**
 * Урок 5 · Очереди: синхронный код, микрозадачи, `setTimeout`.
 *
 * Что здесь: три очереди на таймингах · продолжение промиса идёт раньше
 * `setTimeout` · несловленный отказ роняет процесс · промис нельзя отменить ·
 * схема очередей.
 *
 *   node lessons/lesson-05/examples/03-microtasks.ts     запустить
 *   yarn typecheck                                       проверить типы
 */

const pause = (ms: number): Promise<void> => new Promise((resolve) => setTimeout(resolve, ms));

const t0 = Date.now();
// Округляем крупно: важно только «на нуле» против «через полсотни миллисекунд».
const at = (): string => `t≈${Math.round((Date.now() - t0) / 50) * 50}мс`;

// ── Три очереди в одном потоке ─────────────────────────────────────────────
// JavaScript однопоточен. Очередей у него три, и разбираются они по порядку:
//
//   1. синхронный код     — весь, до последней строки
//   2. микрозадачи        — продолжения промисов (.then и всё после await)
//   3. макрозадачи        — setTimeout, setInterval, ввод-вывод
//
// Это прямое продолжение урока 4: там мы выяснили, что setTimeout ждёт конца
// синхронного кода. Уточнение: промисы ждут того же, но встают ВПЕРЕДИ него,
// даже если у setTimeout нулевая задержка.
async function orderDemo(): Promise<void> {
  setTimeout(() => console.log('3) setTimeout — последним ', at()));
  void Promise.resolve().then(() => console.log('2) микрозадача — вторым', at()));
  console.log('1) синхронный код — первым', at());
  await pause(50);
  console.log('4) после await pause(50) ', at());
}
await orderDemo();

// Смотреть надо на тайминги, а не на порядок строк. Строки 2 и 3 печатаются
// на нулевой миллисекунде — то есть ДО того, как пауза вообще началась идти.
// Порядок «сначала дождались паузы, потом промис, потом setTimeout» описывал бы
// картину, в которой await блокирует программу. Он её не блокирует.

// ── await останавливает функцию, а не программу ────────────────────────────
// Пока orderDemo стояла на await pause(50), процесс был занят: он успел
// разобрать обе очереди. Видно на счётчике, который тикает независимо.
let ticks = 0;
const timer = setInterval(() => {
  ticks += 1;
}, 10);
await pause(100);
clearInterval(timer);
console.log('5) за 100 мс ожидания фоновый таймер тикнул раз:', ticks);

// Сравнение с точкой останова в отладчике здесь не работает: брейкпойнт
// замораживает всё, await — только текущую функцию.

// ── Несловленный отказ роняет процесс ──────────────────────────────────────
// Это единственная демонстрация урока, которой нет в файле: она его убивает.
// Запустить отдельной командой:
//
//   node -e "
//   async function angry() { throw new Error('внутри async'); }
//   angry();
//   console.log('этот лог напечатался');
//   "
//
// Вывод:
//
//   этот лог напечатался
//   [eval]:2
//   async function angry() { throw new Error('внутри async'); }
//                                  ^
//   Error: внутри async
//
// Код досчитал до конца, напечатал свою строку — и только потом процесс умер.
// Ошибка пришла ПОСЛЕ того, как всё «прошло успешно». Именно так это выглядит
// в прогоне тестов: упало не там, где сломано.
//
// То же самое роняет и .finally без .catch после него — см. 02-then-catch-finally.ts:
//
//   node -e "Promise.reject(new Error('отказ')).finally(() => console.log('finally отработал'));"

// ── Промис нельзя отменить ─────────────────────────────────────────────────
// Ни promise.cancel(), ни способа остановить уже запущенную работу в языке нет.
// Единственное, что можно, — перестать её ЖДАТЬ.
let backgroundFinished = false;
const background = pause(80).then(() => {
  backgroundFinished = true;
  return 'фоновая работа';
});

const winner = await Promise.race([background, pause(20).then(() => 'таймаут')]);
console.log('6) гонку выиграл:', winner, '· фоновая доработала?', backgroundFinished);

await pause(100);
console.log('7) а теперь доработала?', backgroundFinished, '← её никто не отменял');

// В тестах это значит: после того как шаг «упал по таймауту», фоновая работа
// продолжает менять состояние страницы. Цифрами то же самое — в 06-many-promises.ts.

// ── Схема: что откуда перетекает ───────────────────────────────────────────
//
//   синхронный код ──► очередь микрозадач ──► ОДНА макрозадача ──► снова микрозадачи ──► …
//                       (разбирается до дна,     (setTimeout,
//                        включая добавленные      setInterval,
//                        по ходу)                 ввод-вывод)
//
// «До дна» — значит, микрозадача, которую добавила другая микрозадача, тоже
// успевает раньше любого setTimeout:
await new Promise<void>((done) => {
  setTimeout(() => {
    console.log('10) макрозадача');
    done();
  });
  void Promise.resolve().then(() => {
    console.log('8) микрозадача');
    void Promise.resolve().then(() => console.log('9) микрозадача, добавленная микрозадачей'));
  });
});

