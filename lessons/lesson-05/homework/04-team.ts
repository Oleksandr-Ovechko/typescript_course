function repeatTimes(times: number, action: (round: number) => void): void {
  for (let round = 1; round <= times; round++) {
    action(round); // [C] порядок: …
  }
}

const team = {
  title: 'Команда',
  members: ['Ann', 'Bob'],
  listMembers(): string[] {
    const lines: string[] = []; // [A] порядок: …
    repeatTimes(this.members.length, (round) => {
      lines.push(`${this.title}: ${this.members[round - 1]}`); // [D] порядок: …
    }); // [B] repeatTimes закончилась — порядок: …
    return lines; // [E] порядок: …
  },
};

