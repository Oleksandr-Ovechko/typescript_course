// ── Ленивый квантификатор: вопрос с занятия ───────────────────────────────
const quoted = 'say "Mon" and "Tue"';

console.log('1)', quoted.match(/".*?"/g));
// → 1)
// почему первое совпадение — "Mon", а не что-то, начинающееся с say?

console.log('2)', (quoted.match(/.*?/g) ?? []).length);
// → 2)
// сколько символов в quoted? что именно нашлось — символы или что-то другое?

console.log('3)', quoted.match(/.*/g));
// → 3)
// жадный вариант той же записи: почему совпадений не одно?

// ── Первое или последнее ──────────────────────────────────────────────────
console.log('4)', /(\d+) USD/.exec('10 EUR 25 USD 30 USD')?.[1]);
// → 4)

console.log('5)', '10 EUR 25 USD 30 USD'.match(/(\d+) USD/g));
// → 5)
// чем отличается от 4) и почему здесь нет одних чисел без « USD»?

// ── Приоритет | ───────────────────────────────────────────────────────────
console.log('6)', ['Save', 'Cancel', 'Save draft', 'Do not cancel', 'Cancel order'].filter((l) => /^Save|Cancel$/.test(l)));
// → 6)

// ── Ловушка g ─────────────────────────────────────────────────────────────
const digit = /\d/g;
console.log('7)', ['a1', 'b2', 'c3', 'd4'].map((s) => digit.test(s)));
// → 7)
// чему равен digit.lastIndex перед каждым вызовом?

// ── split с группой ───────────────────────────────────────────────────────
console.log('8)', '5:30pm'.split(/(:|am|pm)/), '5:30pm'.split(/(?::|am|pm)/));
// → 8)

