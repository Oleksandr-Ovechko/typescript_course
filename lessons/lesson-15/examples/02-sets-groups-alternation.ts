// ── Наборы и диапазоны ─────────────────────────────────────────────────────
// […] — ОДИН символ из перечисленных. [a-z] — диапазон. [^…] — любой, КРОМЕ.
console.log('1)', ['grey', 'gray', 'groy'].filter((w) => /^gr[ae]y$/.test(w)));
console.log('2)', /^[A-Za-z]+$/.test('AbC'), /^[^A-Za-z]+$/.test('1-2_3'), /^[^A-Za-z]+$/.test('1-b'));

// ^ значит разное по месту: в начале шаблона — якорь «начало строки»,
// первым символом внутри […] — «кроме».

// ── Кириллица в диапазоне ──────────────────────────────────────────────────
// Диапазон идёт по номерам символов в Unicode. Буква ё стоит вне а–я.
console.log('3)', /^[а-я]+$/.test('ёлка'), /^[а-яё]+$/.test('ёлка'));

// ── Внутри […] спецсимволы — обычные ───────────────────────────────────────
// [\d,.]+ — «цифры, запятые и точки, сколько угодно»: так выглядит сумма.
// [.+] — «точка или плюс», не «любой символ» и не квантификатор.
console.log('4)', /^[\d,.]+$/.test('1,234.50'), /^[.+]$/.test('.'), /^[.+]$/.test('x'));

// Особые внутри набора — только ], \, ^ в начале и - между символами.

// ── Скобочные группы ───────────────────────────────────────────────────────
// Скобки делают две вещи: запоминают совпавший кусок и объединяют кусок,
// чтобы квантификатор действовал на него целиком.
// В массиве match после нулевого элемента — группы, по порядку открывающих скобок.
const m5 = '5:30'.match(/^(\d{1,2}):(\d{2})$/);
console.log('5)', m5?.slice(0, 3));
const [, hours, minutes] = m5 ?? [];
console.log('6)', hours, minutes);

// const [, hours, minutes] — деструктуризация с пропуском нулевого элемента.

// ── Три вида скобок ────────────────────────────────────────────────────────
// ( )        — нумерованная группа: запоминается, достаётся по номеру;
// (?: )      — без запоминания: только объединяет, в массив не попадает;
// (?<имя> )  — именованная: запоминается и достаётся по имени через groups.
console.log('7)', '5'.match(/^(\d{1,2})(?::(\d{2}))?$/)?.slice(0, 3), /^(?:ab)+$/.test('ababab'));
const date = '2026-10-15'.match(/(?<year>\d{4})-(?<month>\d{2})-(?<day>\d{2})/);
console.log('8)', date?.groups?.year, date?.groups?.day);

// 7) — (?::(\d{2}))? — «двоеточие и минуты — оба или ничего». Минут нет —
//      на месте группы 2 undefined. (?:ab)+ — повторить пару целиком.
// 8) — ?. здесь нужен потому, что match может вернуть null (совпадения нет),
//      а groups бывает undefined (в шаблоне нет именованных групп).
//      TypeScript требует учесть оба случая.

// ── Обратные ссылки ────────────────────────────────────────────────────────
// \1 внутри шаблона — «здесь тот же ТЕКСТ, что совпал с первой группой».
// Не тот же шаблон — тот же текст. \2 — со второй, и так далее.
// projects/monolith/tests/regression-run/app-drawer-reports/staff/payroll-summary/C22831.helpers.ts:307
const sameYear = /January 01, (\d{4}) - December 31, \1/;
console.log('9)', sameYear.test('Payroll Summary, January 01, 2025 - December 31, 2025'),
  sameYear.test('Payroll Summary, January 01, 2025 - December 31, 2026'));
console.log('10)', /^(["']).*\1$/.test(`"hi"`), /^(["']).*\1$/.test(`"hi'`));

// 9)  — «отчёт за один и тот же год, какой бы он ни был».
// 10) — закрывающая кавычка должна быть той же, что открывающая.

// ── Альтернация ────────────────────────────────────────────────────────────
// | — «или» для целых кусков (набор […] — это один символ).
// У | самый низкий приоритет: он делит весь шаблон, если его не взять в скобки.
const buttons = ['Save', 'Cancel', 'Save draft'];
console.log('11)', buttons.filter((l) => /^(Save|Cancel)$/.test(l)));
console.log('12)', buttons.filter((l) => /^Save|Cancel$/.test(l)));

// 12) — /^Save|Cancel$/ читается как «^Save» ИЛИ «Cancel$»,
//       и 'Save draft' проходит по первой половине.

// ── Регулярка из проекта — вместе с кодом вокруг ───────────────────────────
// helpers/monolith/components/schedule.ts:194-202. Шаблон сам по себе:
const timeRe = /^(\d{1,2})(?::?(\d{2}))?(am|pm)$/;
console.log('13)', '5:30pm'.match(timeRe)?.slice(1, 4), '5pm'.match(timeRe)?.slice(1, 4), timeRe.test('5:30'));

// По кускам: одна-две цифры часов (группа 1) · необязательно: двоеточие,
// которого может и не быть (:?), и две цифры минут (группа 2) — всё вместе
// в (?:…)? · am или pm (группа 3).
//
// Сам по себе шаблон не берёт '7 PM': заглавные буквы и пробел.
console.log('14)', timeRe.test('7 PM'));

// Но в проекте шаблон не получает строку как есть. Функция целиком.
// Две вещи в ней — из следующих файлов: replace(/\s+/g, '') — «все куски
// пробелов заменить пустой строкой» (03), new RegExp с двойным \\ — (04).
function buildTimeRegex(input: string): RegExp {
  const s = input.trim().toLowerCase().replace(/\s+/g, '');
  const m = s.match(/^(\d{1,2})(?::?(\d{2}))?(am|pm)$/);
  if (!m) throw new Error(`Invalid time: "${input}". Use like '5am', '5:00am', '12 am', '7 PM'.`);

  const [, hh, mm, ap] = m;
  const mmPart = mm ? `:?${mm}` : '(?::?00)?';
  return new RegExp(`^\\s*${hh}${mmPart}\\s*${ap}\\s*$`, 'i');
}
console.log('15)', buildTimeRegex('7 PM'), buildTimeRegex('7 PM').test(' 7:00 PM '));

// Первая строка функции переводит вход в нижний регистр и убирает пробелы:
// '7 PM' → '7pm', и шаблон совпадает. '7 PM' даже назван правильным
// форматом в сообщении об ошибке. А итоговая регулярка — с флагом i.
// Вывод: шаблон, вынутый из кода (например, на regex101), теряет строки
