// ── Чей метод ──────────────────────────────────────────────────────────────
// Методы делятся не по записи регулярки (/…/ или new RegExp — объект один),
// а по тому, У КОГО их вызывают:
//
//   регулярка.test(строка)        → true / false
//   регулярка.exec(строка)        → одно совпадение с группами или null
//   строка.match(регулярка)       → без g — как exec; с g — все совпадения, без групп
//   строка.matchAll(регулярка)    → все совпадения С группами; нужен g
//   строка.search(регулярка)      → позиция первого совпадения или -1
//   строка.split(регулярка)       → массив кусков между совпадениями
//   строка.replace(регулярка, …)  → новая строка
//   строка.replaceAll(…, …)       → новая строка
console.log('1)', typeof /a/.test, typeof /a/.exec, typeof new RegExp('a').exec);

// У регулярки match нет — это метод строки:
const re: object = /a/;
console.log('2)', 'match' in re, 'match' in String.prototype);

// ── exec — первое совпадение ───────────────────────────────────────────────
// Флаг g — «все совпадения, а не первое». Без него exec и match возвращают
// ПЕРВОЕ подходящее место.
console.log('3)', /(\d+) USD/.test('Total 25 USD'), /(\d+) USD/.exec('Total 25 USD')?.[1]);
console.log('4)', /(\d+) USD/.exec('25 USD 30 USD')?.[1], /(\d+) USD/.exec('Total 25 30 USD')?.[1]);

// 4) — во второй строке нашлось 30, но не потому, что оно последнее:
//      после 25 идёт пробел и 30, а не « USD». Первое место, где шаблон
//      совпал целиком, — «30 USD».

// ── match с g и без ────────────────────────────────────────────────────────
console.log('5)', 'a1 b22 c333'.match(/\d+/), 'a1 b22 c333'.match(/\d+/g));

// Один и тот же match возвращает разное в зависимости от g.
// Нужны все совпадения И группы — matchAll:
console.log('6)', [...'a1 b22 c333'.matchAll(/([a-z])(\d+)/g)].map((m) => `${m[1]}=${m[2]}`));

// ── search и split ─────────────────────────────────────────────────────────
console.log('7)', 'a1 b22'.search(/\d/), 'ab'.search(/\d/));
console.log('8)', 'a, b,c ,d'.split(/\s*,\s*/));

// Если в шаблоне split есть группа, её текст ПОПАДАЕТ в результат:
console.log('9)', 'a, b'.split(/\s*(,)\s*/), 'a, b'.split(/\s*(?:,)\s*/));

// ── replace и replaceAll ───────────────────────────────────────────────────
// replace со строкой меняет только первое вхождение; все — регулярка с g
// или replaceAll.
console.log('10)', '1 000 000'.replace(' ', ''), '1 000 000'.replace(/ /g, ''), '1 000 000'.replaceAll(' ', ''));

// replaceAll с регуляркой требует флаг g — без него падает:
try {
  '1 000 000'.replaceAll(/ /, '');
} catch (e) {
  console.log('11)', e instanceof TypeError, (e as Error).message);
}

// ── Группы в строке замены ─────────────────────────────────────────────────
// Во втором аргументе replace $1, $2, $3 — текст групп. Это синтаксис
// строки замены, обычная строка в одинарных кавычках. С обратными ссылками
// \1 (внутри шаблона) и с $0 / $1 в консоли браузера (урок 16) — совпадает
// только по виду.
console.log('12)', '2026-10-15'.replace(/(\d{4})-(\d{2})-(\d{2})/, '$3.$2.$1'));

// «Всё, кроме цифр и точки» — так из цены делают число
// (helpers/monolith/setup/services/service-setup-page.ts:206):
console.log('13)', '1,234.50 USD'.replace(/[^\d.]/g, ''));

// ── Ловушка: g и test ──────────────────────────────────────────────────────
// Регулярка с g помнит, где остановилась, — в свойстве lastIndex.
// Следующий test ищет дальше этого места, какую строку ему ни передай.
const gRe = /a/g;
console.log('14)', gRe.test('aa'), gRe.lastIndex, gRe.test('aa'), gRe.lastIndex, gRe.test('aa'), gRe.lastIndex);

// После второго совпадения lastIndex = 2 — дальше 'aa' искать нечего: false,
// и lastIndex сбрасывается в 0. Для test флаг g не нужен.

// ── Флаги ──────────────────────────────────────────────────────────────────
// i — регистр не важен           g — все совпадения
// m — ^ и $ у каждой строки      s — точка ловит и перевод строки
// u — символ Unicode целиком     y — искать ровно с lastIndex
// d — exec отдаёт позиции групп  v — расширенный u (ES2024)
console.log('15)', 'A\na'.match(/^a/gim), 'A\na'.match(/^a/g));
console.log('16)', /a.b/.test('a\nb'), /a.b/s.test('a\nb'));
console.log('17)', /^.$/.test('😀'), /^.$/u.test('😀'));
const sticky = /\d/y;
sticky.lastIndex = 1;
console.log('18)', sticky.test('a1'), sticky.lastIndex);
const withD = /(\d+)/d.exec('id=42');
console.log('19)', withD?.indices?.[1]);

// 15) — с m якорь ^ срабатывает в начале каждой строки текста.
// 16) — текст со страницы часто многострочный; вместо точки в проекте
//       пишут [\s\S] — «любой символ вообще».
