// ── Описание формы строки ──────────────────────────────────────────────────
// /Save/ — «где-то внутри есть Save». test отвечает true или false.
const labels = ['Save', 'Save draft', 'Unsaved changes', 'save'];
console.log('1)', labels.filter((l) => /Save/.test(l)));

// Подошёл и 'Save draft'. 'Unsaved changes' — нет: внутри 'saved' с маленькой,
// а регулярка различает регистр.

// ── Якоря и флаг ───────────────────────────────────────────────────────────
// ^ — «здесь начало строки», $ — «здесь конец». Это места, а не символы,
// и пишутся они внутри шаблона. Буква после закрывающей черты — флаг,
// настройка всего шаблона: i — не различать регистр.
console.log('2)', labels.filter((l) => /^Save$/.test(l)), labels.filter((l) => /^save$/i.test(l)));

// ── Что стоит в конце строки ───────────────────────────────────────────────
// В строке нет обязательного «последнего символа» — только то, что в неё
// положили. В подписи 'Save' перевода строки нет. Он появляется, когда текст
// прочитан со страницы вместе с отступами разметки (урок 16).
// В JavaScript $ без флага m — строго конец строки, даже перед последним \n:
console.log('3)', /Save$/.test('Save\n'), /Save$/m.test('Save\n'), /^\s*Save\s*$/.test('Save\n'));

// Последняя запись — «Save, а вокруг сколько угодно пробелов и переносов».
// Такие шаблоны в проекте стоят там, где текст берут со страницы.

// ── Вторая запись — new RegExp ─────────────────────────────────────────────
// Регулярка — объект класса RegExp (урок 13). /…/ — литерал, короткая запись;
// new RegExp(шаблон, флаги) — то же самое, собранное из строки.
const lit = /^Save$/i;
const obj = new RegExp('^Save$', 'i');
console.log('4)', lit.test('SAVE'), obj.test('SAVE'), lit.source, lit.flags);

// Объект один и тот же — с тем же прототипом и теми же методами.
// Разные записи, а не разные виды регулярок.
console.log('5)', Object.getPrototypeOf(lit) === RegExp.prototype, Object.getPrototypeOf(obj) === RegExp.prototype);

// Зачем тогда вторая запись — в 04-escaping-lookaround.ts: когда кусок
// шаблона берётся из переменной.

// ── match — что именно совпало ─────────────────────────────────────────────
// match — метод строки. Регулярка передаётся ему аргументом.
// [0] — совпавший кусок, index — где. Не нашлось — null.
console.log('6)', 'Save draft'.match(/draft/), 'Save draft'.match(/cancel/));

// Из-за этого null после match почти всегда стоит ?. (урок 3):
// «если слева null или undefined — дальше не идём, результат undefined».

// ── Символьные классы ──────────────────────────────────────────────────────
// \d — цифра, \w — латинская буква, цифра или _, \s — пробел, табуляция,
// перевод строки, . — любой символ, кроме конца строки (\n, \r, \u2028, \u2029).
// Заглавная буква — обратный класс: \D \W \S. У точки обратного нет.
// Класс — это ОДИН символ.
console.log('7)', /\d/.test('Room 12'), /^\d$/.test('7'), /^\d$/.test('12'));
console.log('8)', /^\w$/.test('Z'), /^\w$/.test('Ж'), /^\S$/.test('Ж'));
console.log('9)', /a\sb/.test('a\nb'), /^a.b$/.test('a-b'), /^a.b$/.test('a\nb'));

// 7) — ^\d$ — ровно одна цифра, «12» не подходит.
// 8) — \w кириллицу буквой не считает: «Иван» под \w не подходит, под \S — да.
// 9) — \s ловит перевод строки, точка — нет.

// ── Граница слова ──────────────────────────────────────────────────────────
// \b — не символ и не флаг, а место: между символом \w (латиница, цифра, _)
// и не-\w. Кириллица для \w не буква — поэтому с ней \b не работает.
console.log('10)', /\bcat\b/.test('a cat here'), /\bcat\b/.test('catalog'), /\bкот\b/.test('a кот b'));

// ── Квантификаторы ─────────────────────────────────────────────────────────
// Сколько раз повторить то, что стоит ПЕРЕД ним:
// * — 0 и больше, + — 1 и больше, ? — 0 или 1,
// {n} — ровно n, {n,} — n и больше, {n,m} — от n до m.
console.log('11)', /^\d{4}$/.test('2026'), /^\d{2,3}$/.test('2026'), /^\d{2,}$/.test('2026'));
console.log('12)', /^colou?r$/.test('color'), /^colou?r$/.test('colour'), /^\d+$/.test(''), /^\d*$/.test(''));

// 12) — + на пустой строке — нет, * — да: «ноль раз» тоже считается.

// ── Жадный и ленивый ───────────────────────────────────────────────────────
// По умолчанию квантификатор жадный: берёт как можно больше и отдаёт назад,
// только если иначе не совпадёт. ? после квантификатора делает его ленивым:
// как можно меньше.
const quoted = 'say "Mon" and "Tue"';
console.log('13)', quoted.match(/".*"/)?.[0]);
console.log('14)', quoted.match(/".*?"/)?.[0]);

// 13) — .* дошёл до последней кавычки. 14) — до ближайшей.
// Совпадение начинается с первой кавычки, потому что шаблон с неё начинается:
// в 'say' кавычки нет.

// ── Ленивый квантификатор без опоры ────────────────────────────────────────
// Если вокруг .*? ничего нет, «как можно меньше» — это ноль символов.
// С флагом g («все совпадения, а не первое», подробно — 03-methods-flags.ts)
// такой шаблон находит
// пустую строку на каждой позиции: 19 символов + позиция в самом конце.
const lazyAlone = quoted.match(/.*?/g) ?? [];
console.log('15)', quoted.length, lazyAlone.length, lazyAlone.slice(0, 3));

// Ленивому квантификатору нужна опора справа — как кавычка в 14).

