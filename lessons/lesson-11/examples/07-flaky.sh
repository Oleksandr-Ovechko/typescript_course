#!/usr/bin/env bash
# Урок 11 · Флейки-тест: зелёный прогон, который врёт
#
# Что здесь: упал, ретрай прошёл — код возврата 0 и «1 flaky» · трейс есть,
# но от ПРОШЕДШЕЙ попытки · для сравнения тест, упавший и на ретрае ·
# как получить трейс самого падения.
#
#   bash lessons/lesson-11/examples/07-flaky.sh
#   cd /tmp/wl-pw-examples/flaky                    # песочница остаётся

source "$(dirname "$0")/_sandbox.sh" flaky

say "Флейки-тест: tests/flaky.spec.ts"
cat tests/flaky.spec.ts
cat <<'TEXT'
  Страница ?location=new — «холодный кэш»: первый запрос к API после старта
  сервера отвечает 2,5 с, а expect ждёт 2 с. Первая попытка падает, ретрай
  проходит. Сервер стартует заново на каждый прогон, поэтому так будет
  каждый раз.
TEXT

# ── Как в проекте: retries 1, trace 'on-first-retry' ─────────────────────────
say "Прогон с конфигом как в проекте"
run $PW test tests/flaky.spec.ts 2>&1 | grep -E '✘|✓|flaky$|failed$|passed|код возврата'
find test-results -type f | sort
cat <<'TEXT'
  Код возврата 0 — прогон зелёный. CI, скрипты и TestRail увидят «прошёл».
  Единственный след проблемы — «1 flaky» в итоге.

  И трейс ЕСТЬ — в папке -retry1. Но это трейс прошедшей попытки: в нём всё
  хорошо, падения в нём нет. От упавшей попытки осталась только папка
  с error-context.md: 'on-first-retry' пишет трейс на ретрае — каким бы ни
  оказался результат ретрая.
TEXT

# ── Для сравнения: упал и на ретрае ──────────────────────────────────────────
say "Для сравнения: book Pilates падает и на ретрае"
run $PW test tests/booking.spec.ts:14 2>&1 | grep -E '✘|✓|flaky$|failed$|passed|код возврата'
find test-results -type f | sort
cat <<'TEXT'
  Код возврата 1, прогон красный. Трейс снова в -retry1 — и на этот раз
  в нём падение. То есть трейс в проекте есть всегда, когда был ретрай;
  вопрос только в том, что именно в нём записано.
TEXT

# ── Как увидеть само падение ─────────────────────────────────────────────────
say "Флейки своим конфигом: retries 0, trace 'retain-on-failure'"
run $PW test tests/flaky.spec.ts -c playwright.my.config.ts 2>&1 | grep -E '✘|✓|flaky$|failed$|passed|код возврата'
find test-results -type f | sort
cat <<'TEXT'
  Теперь флейки просто красный: ретрая нет, и трейс, скриншот и видео
  лежат у упавшей попытки. Так флейки и разбирают — своим конфигом,
  а не проектным. Если падение редкое, добавляют --repeat-each=10:
  тест прогонится десять раз (повторы расходятся по воркерам).
TEXT
