#!/usr/bin/env bash
# Урок 11 · Что остаётся после падения и HTML-отчёт
#
# Что здесь: с настройками проекта трейс есть только у ретрая · у прошедших
# тестов папок нет вовсе · свой конфиг поверх общего: скриншот, видео,
# трейс у первой же попытки, HTML-отчёт · отчёт собирается и при зелёном
# прогоне — open управляет только тем, открывать ли его в браузере.
#
#   bash lessons/lesson-11/examples/04-artifacts-and-report.sh
#   cd /tmp/wl-pw-examples/artifacts-and-report     # песочница остаётся

source "$(dirname "$0")/_sandbox.sh" artifacts-and-report

# ── Настройки проекта: retries 1, trace 'on-first-retry' ─────────────────────
say "Прогон с конфигом как в проекте"
run $PW test tests/booking.spec.ts 2>&1 | grep -E '^Running|✘|✓|failed$|passed|код возврата'

say "Что осталось на диске"
find test-results -type f | sort
cat <<'TEXT'
  Три вещи, которые стоит увидеть глазами.

  1. Папки есть только у УПАВШЕГО теста. Два прошедших не оставили ничего.
  2. У первой попытки — только error-context.md: текст ошибки, кусок
     исходника и страница, записанная текстом. Файл кладётся рядом с каждой
     упавшей попыткой — в первую очередь для ИИ, который разбирает падение.
  3. trace.zip — только в папке с «-retry1»: 'on-first-retry' значит
     «писать трейс, когда тест пошёл на первый повтор». Так и в wl-e2e:
     трейс ищут в папке с -retry1 на конце.

  Видео и скриншота нет: в конфигах проекта они выключены.
  .last-run.json — список упавших тестов: по нему работает --last-failed.
TEXT

say "Перезапустить только упавшие: --last-failed"
run $PW test --last-failed --retries=0 2>&1 | grep -E '^Running|✘|✓|код возврата'

# ── Свой конфиг поверх общего ────────────────────────────────────────────────
say "Свой конфиг: playwright.my.config.ts"
cat playwright.my.config.ts
cat <<'TEXT'
  ...base — все ключи общего конфига, как спред объекта из урока 3.
  Дальше перечислено только то, что отличается. Общий конфиг не тронут.
TEXT

say "Тот же прогон своим конфигом"
run $PW test tests/booking.spec.ts -c playwright.my.config.ts 2>&1 | grep -E '^Running|✘|✓|failed$|passed|код возврата'
find test-results -type f | sort
cat <<'TEXT'
  retries: 0 — второй попытки нет, а трейс, скриншот и видео лежат
  у первой же: 'retain-on-failure' пишет всегда и оставляет только
  у упавших. Папки test-results/ перезаписываются каждым прогоном:
  прошлых результатов там уже нет.
TEXT

# ── HTML-отчёт ──────────────────────────────────────────────────────────────
say "HTML-отчёт после зелёного прогона"
rm -rf playwright-report
run $PW test tests/booking.spec.ts:8 -c playwright.my.config.ts 2>&1 | grep -E 'passed|failed$|код возврата'
ls playwright-report
cat <<'TEXT'
  Тест прошёл, а отчёт собран. У html-репортера `open` отвечает НЕ за то,
  собирать ли отчёт, а за то, открывать ли его в браузере сам:
    'on-failure' — открыть, если что-то упало (это значение по умолчанию)
    'always'     — открывать всегда
    'never'      — не открывать, только сложить на диск
  И в любом случае отчёт не откроется сам в CI, когда у запуска нет
  терминала и когда тесты запускает ИИ-агент — так написано в исходнике
  html-репортера. Когда прогон гоняет Клод, отчёт только складывается.
  В этих примерах стоит PLAYWRIGHT_HTML_OPEN=never (см. _sandbox.sh) —
  переменная окружения перебивает `open` из конфига, чтобы примеры
  не открывали окна. Посмотреть отчёт:
    cd /tmp/wl-pw-examples/artifacts-and-report
    node_modules/.bin/playwright show-report

  show-report открывает ПОСЛЕДНИЙ собранный отчёт. В wl-e2e html-репортера
  в конфигах monolith и widgets нет, поэтому `yarn report` покажет старый
  отчёт — если он где-то остался — или скажет, что отчёта нет. Свежий —
  только своим конфигом или флагом --reporter=list,html.
TEXT
